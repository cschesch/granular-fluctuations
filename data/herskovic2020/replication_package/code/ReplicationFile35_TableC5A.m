    Ntop = ceil(N * exp(X) ./ (1 + exp(X)));

    theta_hat = theta_guess;
    theta_hat(end) = Ntop;

    disp([num2str((toc/60),'%.2f'),' minutes'])

    [out, ModelNewFirms] = NewFirmVol(Ntop,theta_hat,N,nloop,loc_exclude,FracNewFirms);

