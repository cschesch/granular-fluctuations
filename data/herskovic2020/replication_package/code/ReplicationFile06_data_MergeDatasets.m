clear, addpath(genpath('functions\'))

%**************************************************************************
% Load
%**************************************************************************
load('../output/CleanData/CRSPDAILY July2017');   % generated by 'ReplicationFile02_data_Construct_Annual_Stock_RV_Daily_CRSP.m'
load('../output/CleanData/CRSPMONTHLY July2017'); % generated by 'ReplicationFile03_data_Construct_ME_EXCHCD_SIC_Monthly_CRSP.m'
load('../output/CleanData/COMPUSTAT July2017');   % generated by 'ReplicationFile04_data_Construct_Annual_Sales_Qrt_Compustat.m'
load('../output/CleanData/LINKAGES 170301');      % generated by 'ReplicationFile05_data_BuildLinkageMatrices.m'

permlist            = union(union(CRSPDAILY.permlist,CRSPMONTHLY.permlist),union(COMPUSTAT.permlist,LINKAGES.permlist));
yrlist              = CRSPDAILY.yrlist;
N                   = length(permlist);
T                   = length(yrlist);
fields              = setdiff(union(union(fieldnames(COMPUSTAT),fieldnames(CRSPDAILY)),union(fieldnames(CRSPMONTHLY),fieldnames(LINKAGES))),[{'permlist'},{'yrlist'}]);

% COMPUSTAT ADJUSTMENT
COMPUSTAT.SALES(COMPUSTAT.yrlist<1965,:)        = nan;
COMPUSTAT.SALESVOL1Y(COMPUSTAT.yrlist<1965,:)   = nan;
COMPUSTAT.SALESVOL5Y(COMPUSTAT.yrlist<1965,:)   = nan;
COMPUSTAT.GIC(COMPUSTAT.yrlist<1965,:)          = nan;

% ALL
structlist = [{'CRSPDAILY'},{'CRSPMONTHLY'},{'COMPUSTAT'},{'LINKAGES'}];
for j=1:length(structlist)
    structname          = char(structlist(j));
    [~,ia,ib]           = intersect(permlist,eval([structname '.permlist']));
    [~,iat,ibt]         = intersect(yrlist,eval([structname '.yrlist']));
    fields              = setdiff(fieldnames(eval(structname)),[{'permlist'},{'yrlist'}]);
    for i=1:length(fields)
        eval(['ALL.' char(fields(i)) ' = nan(T,N);']);
        eval(['ALL.' char(fields(i)) '(iat,ia) = ' structname '.' char(fields(i)) '(ibt,ib);']);
    end
    clear fields
end
ALL.yrlist  = yrlist;
ALL.permlist= permlist;
save('../output/CleanData/ALL DATA MERGED July2017','ALL')