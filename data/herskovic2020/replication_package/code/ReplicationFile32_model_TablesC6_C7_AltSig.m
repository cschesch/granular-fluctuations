    case 2
        load(['../output/EstimationResults/theta_AltSig2.mat']) % generated by "ReplicationFile31_model_AltID.m"
        theta = estimation.theta_guess(1:8);
        FVAL  = estimation.FVAL_guess;
    case 3
        load(['../output/EstimationResults/theta_AltSig3.mat']) % generated by "ReplicationFile31_model_AltID.m"
        load(['../output/EstimationResults/se_matrices_AltSig3.mat']) % generated by "ReplicationFile31_model_AltID.m"
        theta = estimation.theta_guess(1:8);
        FVAL  = estimation.FVAL_guess;
end

if col == 1 || col == 3

    loc_exclude            = estimation.loc_exclude;
    model_moments_NormX    = estimation.model_moments_NormX;
    data_moments_NormX     = estimation.data_moments_NormX;
    h_moments              = model_moments_NormX - data_moments_NormX;
    h_moments(loc_exclude) = [];


    G_neg          = hessian.G_neg;
    G_pos          = hessian.G_pos;

    W              = estimation.W;
    g_cov          = hessian.g_cov;
    nloop          = hessian.nloop;
    T              = hessian.T;


    tau = T/nloop;

    % s.e. of all parameters
    G0 = (G_neg + G_pos) * 0.5;
    A  = inv(G0' * W * G0);
    B  = G0' * W * g_cov * W' * G0;
    AsynCov   = (1 + tau) * A * B * A; % this is the asymptotic variance-covariance matrix of sqrt(T) * (theta_hat - theta_true)
    theta_cov = AsynCov / T;
    se        = sqrt(diag(theta_cov));

    % Wald test -- Standard GMM test - Testing correlation moments?
    loc_corr = [1:28];
    H = G0(loc_corr,:);
    h = h_moments(loc_corr);
    Wald    = T * h' * pinv(H * AsynCov * H') * h;
    p_value = 1 - chi2cdf(Wald,length(h));


    switch col
        case 1
            tab_moments = [tab_moments, [data_moments_NormX; nan], [model_moments_NormX; FVAL]];
        case 3
            tab_moments = [tab_moments, [model_moments_NormX; FVAL]];
    end
    
else
    model_moments_NormX = estimation.model_moments_guess_NormX;
    se      = nan(size(theta));
    Wald    = nan;
    p_value = nan;
    tab_moments = [tab_moments, [model_moments_NormX; FVAL]];

end

