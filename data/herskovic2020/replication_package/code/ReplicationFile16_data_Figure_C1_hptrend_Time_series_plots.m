%
stdize = @(x) (x - nanmean(x)) ./ nanstd(x);

% Use variance
ALL.STOCKVOL1Y = ALL.STOCKVOL1Y .^ 2;
ALL.SALESVOL1Y = ALL.SALESVOL1Y .^ 2;

h=figure('Color',[1 1 1]);

% Dispersion in size and average volatility
y1 = nanmean(log(ALL.STOCKVOL1Y),2); 
y2 = nanstd(log(ALL.ME),[],2); y2 = lagmatrix(y2,1); [~,y1] = hptrend(y1,50); [~,y2] = hptrend(y2(2:end),50); y2 = [nan;y2];
corr(y1,y2,'rows','pairwise')
subplot(2,2,1)
plot1 = plot((1:length(y2))',stdize(y2),'-k',(1:length(y1))',stdize(y1),'--r','linewidth',2);
set(gca,'fontname','timesnewroman','fontsize',15,'xtick',find(ismember(ALL.yrlist,[1930:20:2010]')),'xticklabel',num2str([1930:20:2010]'),...
    'ylim',[min([stdize(y1);stdize(y2)]) ,max([stdize(y1);stdize(y2)])],'ytick',[-2:3])
set(plot1(2),'Displayname','Mean log vol. (mkt)')
set(plot1(1),'Displayname','Lagged Size dispersion (mkt)')
legend('location','southeast')
xlim([0 92])

% Dispersion in size and dispersion in volatility
