% Solving using fminsearch
XSz(1) = X(6);
XSz(2) = log(X(7));

f = @(XSz) size_moments(XSz,X,N,Ntop,nloop) - [mu_target, sigma_target]';

tic
% fminsearch
options = optimset('TolX',1e-4,'TolFun',1e-4,'Display','iter');%,'MaxIter',500,'MaxFunEval',500);
[Y,FVAL,EXITFLAG] = fminsearch(@(y) sum(f(y) .^ 2), XSz, options);
X(6) =  Y(1);
X(7) =  exp(Y(2));
toc

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Creating moments functions: g   (K by 1)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Moments to exclude: 
loc_exclude = []; % target all moments

theta_0 = [X, Ntop]';   
M = length(theta_0);
all_moments_cov  = MomentsToMatch.all_moments_cov;
all_moments_avg  = MomentsToMatch.all_moments_avg;

