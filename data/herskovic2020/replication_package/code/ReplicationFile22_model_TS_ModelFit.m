compute_model_moments = @(theta) nanmean(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude),2);
compute_model_momentsNormX = @(theta) nanmean(NormX(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude)),2);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Saving Model results (Table of moments)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

x0 =  theta2x(theta_0,N);
W = eye(K);
