% Load estimated parameters
load('../output/EstimationResults/theta_bm.mat') % load benchmarck estimation results
X    = estimation.theta_hat(1:7)';
Ntop = estimation.theta_hat(8);
clear estimation


% Match mean and vol of the size distribution

mu_target    = TS_AvgSz(t);
