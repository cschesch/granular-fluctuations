clear, addpath(genpath('functions\'))
%**************************************************************************
% Load
%**************************************************************************
yrlist  = (1926:2016)';
load('../output/CleanData/Daily RET matrix CRSP shrcd 10-12 1926-2016.mat'); % generated by 'ReplicationFile01_data_Build_Daily_Return_Matrix.m'

% Build RV
T           = length(yrlist);
N           = length(permlist);
yr          = floor(daylist/10000);
STOCKVOL1Y  = nan(T,N);
for t=1:T
    loct                = find(yr==yrlist(t));
    rettmp              = RET(loct,:);
    loci                = find(sum(~isnan(rettmp))>=200);
    STOCKVOL1Y(t,loci)  = sqrt(252)*nanstd(rettmp(:,loci));

    clear rettmp loc*
    t
end
STOCKVOL1Y(STOCKVOL1Y==0) = nan;
CRSPDAILY.permlist      = permlist;
CRSPDAILY.yrlist        = yrlist;
CRSPDAILY.STOCKVOL1Y    = STOCKVOL1Y;
save('../output/CleanData/CRSPDAILY July2017','CRSPDAILY')