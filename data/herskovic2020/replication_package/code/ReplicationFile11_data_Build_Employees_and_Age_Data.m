clear, addpath(genpath('functions\'))



load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
permlist = ALL.permlist;

keepperms = permlist;

fid     = fopen('../data/Employees and Date of IPO annual through 2016.txt');
data    = textscan(fid,'%*n%n%n%*n %*s%*s%*s%*s%*s%n%*s%n','headerlines',1,'delimiter','\t');

permno   = data{1};
datadate = data{2};
emp      = data{3};
ipodate  = data{4};

loc = find(ismember(permno,keepperms));
permno   = permno(loc);
datadate = datadate(loc);
ipodate  = ipodate(loc);
emp      = emp(loc);
clear loc data

ipodate(ipodate==0) = nan;
ipodate = floor(ipodate/10000);

yr = floor(datadate/10000);

yrlist = (1926:2016)';

T = length(yrlist);
N = length(keepperms);

EMP  = nan(T,N);
for i = 1:N
    loc = find(permno==keepperms(i));
    [~, b c] = intersect(yr(loc),yrlist);
    
    EMP(c,i) = emp(loc(b));
    
end        
    
AGE = nan(size(EMP));
for t=1:T;
    AGE(t,:) = sum(~isnan(EMP(1:t,:)),1);
end
    
AGE(AGE==0)=nan;    

save('../output/CleanData/EMP_AGE_matrix_annual_1925_2016_July2017','EMP','AGE');