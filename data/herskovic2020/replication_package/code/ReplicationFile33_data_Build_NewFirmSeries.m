clear, addpath(genpath('functions/'))

%**************************************************************************
% Data
%**************************************************************************

load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
DATA = ALL;
% Zeta regression
logmeannum  = log(nanmean(DATA.CUSTNUM,2));
logtotnum   = log(sum(~isnan(DATA.SALES),2));
logtotnum(isnan(logmeannum)) = nan;

stats       = regstats(logmeannum,logtotnum,'linear','tstat'); 
zeta        = stats.tstat.beta(2);
tzeta       = stats.tstat.t(2);

% All other analysis
DATA.SZ      = DATA.SALES;
DATA.SZlag   = lagmatrix(DATA.SZ,1);
T            = length(DATA.yrlist);
DATA.VARSTK  = DATA.STOCKVOL1Y.^2;
DATA.VARSAL  = DATA.SALESVOL1Y.^2;
DATA.VARSTKnxt  = lagmatrix(DATA.VARSTK,-1);
DATA.VARSALnxt  = lagmatrix(DATA.VARSAL,-1);

DATA.SZGR    = log(DATA.SZ./lagmatrix(DATA.SZ,1));
DATA         = rmfield(DATA,{'SALES','SALESVOL1Y','SALESVOL5Y','STOCKVOL1Y'});

% Limit to 1980-2013 sample
fld     = setdiff(fields(DATA),[{'permlist'}]);
loc     = find(DATA.yrlist >= 1980 & DATA.yrlist <= 2012);
for i=1:length(fld)
    eval(['DATA.' char(fld(i)) ' = DATA.' char(fld(i)) '(loc,:);'])
end
T       = length(loc);
clear loc thous rk t i fld

%**************************************************************************
% Deflator
%**************************************************************************
deflator_type = 'cpiUrb';

deflator.year = (1947:2016)';
aux = xlsread('../data/fred_deflators_annual.xlsx','B15:E84');
deflator.cpiUrb = aux(:,1);
deflator.pceAll = aux(:,2);
deflator.pceExclFoodEnergy = aux(:,3);
deflator.gdpDef = aux(:,4);

eval(['deflator.use = deflator.' char(deflator_type) ';'])
deflator.use_lag  = lagmatrix(deflator.use,1);

[locA,locB] = ismember(deflator.year,DATA.yrlist);
dflt = nan(size(DATA.yrlist));
dflt(locB(locA)) = 1 ./ (deflator.use(locA) / 100);

dflt_lag = nan(size(DATA.yrlist));
dflt_lag(locB(locA)) = 1 ./ (deflator.use_lag(locA) / 100);

DATA.SZDEF     = bsxfun(@times, DATA.SZ, dflt);
DATA.SZDEFlag  = bsxfun(@times, DATA.SZlag, dflt_lag);

DATA.SZ     = DATA.SZDEF;
DATA.SZlag  = DATA.SZDEFlag;
clear deflator dflt

%**************************************************************************
% Time-Series
%**************************************************************************

% Moments:
%    1.  the number of newly public firms in year t relative to the number
%        of existing public firms at (the end of) t-1
%    2.  the market cap of newly public firms in year t relative to the 
%        market cap of all firms in year t
%    3.  the volatility of a typical new firm in year t relative to the 
%        volatility of an existing firm. If it is less fickle, we could 
%        look instead at the 95th percentile of the volatility distribution
%        in each year relative to the average volatility.

varnames = {};
varnames(1) = {'year'};
varnames(2) = {'Number of New Firms'};
varnames(3) = {'Total Number of Firms'};
varnames(4) = {'Fraction of New Firms'};
varnames(5) = {'Fraction of New Mkt Cap'};
varnames(6) = {'Vol of New Firms relative to Existing'};
varnames(7) = {'Vol of New Firms'};
varnames(8) = {'Vol of Old Firms'};
TS.varnames = varnames;

excel_varnames  = {}; excel_varnames(1) = {'year'};
excel_variables = [DATA.yrlist];


filename = 'permno_all';
DTAUSE = DATA;

aux_me     = DTAUSE.ME;
aux_volstk = (DTAUSE.VARSTK);
aux_volsal = (DTAUSE.VARSAL);
    
aux_MENewFirms = nan(size(DTAUSE.yrlist));
aux_NumNewFirms = nan(size(DTAUSE.yrlist));
aux_NumExtFirms = nan(size(DTAUSE.yrlist));

aux_VolStkNewFirms = nan(size(DTAUSE.yrlist));
aux_VolSalNewFirms = nan(size(DTAUSE.yrlist));

aux_VolStkOldFirms = nan(size(DTAUSE.yrlist));
aux_VolSalOldFirms = nan(size(DTAUSE.yrlist));

aux_NumFirms    = sum(~isnan(aux_me),2);
aux_MEFirms     = nansum(aux_me,2);
for t = 2:length(DTAUSE.yrlist)
    loc_new = ~isnan(aux_me(t,:)) & isnan(aux_me(t-1,:));
    aux_NumNewFirms(t) = sum(loc_new);
    aux_MENewFirms(t)  = sum(aux_me(t,loc_new));
    aux_VolStkNewFirms(t) = nanmean(aux_volstk(t,loc_new));
    aux_VolSalNewFirms(t) = nanmean(aux_volsal(t,loc_new));

    aux_VolStkOldFirms(t) = nanmean(aux_volstk(t,~loc_new));
    aux_VolSalOldFirms(t) = nanmean(aux_volsal(t,~loc_new));

    aux_NumExtFirms(t) = sum(isnan(aux_me(t,:)) & ~isnan(aux_me(t-1,:)));
    aux_NumFirms(t)    = sum(~isnan(aux_me(t,:)));

end

aux_TS1 = [aux_NumNewFirms ./ lagmatrix(aux_NumFirms,1)];
aux_TS2 = aux_MENewFirms ./ aux_MEFirms;
aux_TS3 = aux_VolStkNewFirms ./ aux_VolStkOldFirms - 1;
AUX_TS = [DTAUSE.yrlist aux_NumNewFirms aux_NumFirms aux_TS1 aux_TS2 aux_TS3 aux_VolStkNewFirms aux_VolStkOldFirms];
eval(['TS. ' filename '= [AUX_TS];'])

save('../output/CleanData/TS_NewFirms.mat','TS')