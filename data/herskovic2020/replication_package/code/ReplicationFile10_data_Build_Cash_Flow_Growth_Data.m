[~,ix1,ix2] = intersect(permlist,keepperms);

permlist = keepperms;
clear keepperms

% clear Sgr Egr Ngr Pgr

T = size(SA,1);
n = length(permlist);

SA1 = nan(T,n);
EB1 = nan(T,n);
PI1 = nan(T,n);
NI1 = nan(T,n);

logSgr1 = nan(T,n);
logEgr1 = nan(T,n);
logPgr1 = nan(T,n);
logNgr1 = nan(T,n);

SA1(:,ix2) = SA(:,ix1);
EB1(:,ix2) = EB(:,ix1);
PI1(:,ix2) = PI(:,ix1);
NI1(:,ix2) = NI(:,ix1);

logSgr1(:,ix2) = logSgr(:,ix1);
logEgr1(:,ix2) = logEgr(:,ix1);
logPgr1(:,ix2) = logPgr(:,ix1);
logNgr1(:,ix2) = logNgr(:,ix1);

%**************************************************************************
% Sales growth factor model residuals
%**************************************************************************

wSA = SA1 + lagmatrix(SA1,1) + lagmatrix(SA1,2) + lagmatrix(SA1,3);
wts = bsxfun(@rdivide,wSA,nansum(wSA,2));

logSgrresid = nan(size(logSgr1));
factor = nansum(wts.*logSgr1,2);
for i=1:size(logSgr1,2)
    if sum(~isnan(logSgr1(:,i)))<4, continue, end
    stats = regstats(logSgr1(:,i),factor,'linear','r');
    logSgrresid(:,i) = stats.r;
end

clear wts wSA factor stats i

%**************************************************************************
% Build Yearly Data
%**************************************************************************

yrlist = 1926:2016;

T = length(yrlist);
n = length(permlist);

SA = nan(T,n);
EB = nan(T,n);
PI = nan(T,n);
NI = nan(T,n);
Svol = nan(T,n);
Evol = nan(T,n);
Pvol = nan(T,n);
Nvol = nan(T,n);
Sresidvol = nan(T,n);
for t = 1:T
    curr = find(floor(qtrlist/100)==yrlist(t));
    if length(curr)<4, continue, end
    
    SA(t,:) = sum(SA1(curr,:));
    EB(t,:) = sum(EB1(curr,:));
    PI(t,:) = sum(PI1(curr,:));
    NI(t,:) = sum(NI1(curr,:));
    
    if t>T-2, continue, end
    loc  = find(floor(qtrlist/100)>=yrlist(t)&floor(qtrlist/100)<=yrlist(t+2));

    Svol(t,:) = std(logSgr1(loc,:));
    Evol(t,:) = std(logEgr1(loc,:));
    Pvol(t,:) = std(logPgr1(loc,:));
    Nvol(t,:) = std(logNgr1(loc,:));
    Sresidvol(t,:) = std(logSgrresid(loc,:));
end
Svol(Svol==0) = nan;
Evol(Evol==0) = nan;
Pvol(Pvol==0) = nan;
Nvol(Svol==0) = nan;

clear curr EB1 Egr loc log* SA1 Sgr fid ix* n N Ngr NI1 permlist Pgr PI1 qtrlist t T yrlist
save('../output/CleanData/Cashflow_matrix_annual_1925_2016_July2017');


