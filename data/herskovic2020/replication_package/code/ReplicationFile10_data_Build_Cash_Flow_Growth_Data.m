clear, addpath(genpath('functions\'))
%***************************************************************************
% PRELIMINARY DATA MANAGEMENT
%***************************************************************************


fid     = fopen('../data/Income and Sales Qtrly All Firms through 2016.txt');
data    = textscan(fid,'%*n%n%n%*n%*n%*s%*s%*s%*s%*s%*s%*s%n%n%n%n%n%n%*s','headerlines',1,'delimiter','\t');

permno   = data{1};
datadate = data{2};
dpq      = data{3}; % depreciation
niq      = data{4}; % net income
piq      = data{5}; % pretax income
saleq    = data{6}; % sales
xintq    = data{7}; % interest and related expense
xiq      = data{8}; % extraordinary items
clear data

ebitda  = piq + nansum(xintq,2) + nansum(xiq,2) + nansum(dpq,2);
clear dpq xiq xintq

yr              = floor(datadate/10000);
mo              = floor((datadate-yr*10000)/100);
qtr             = nan(size(mo));
qtr(mo<=3)      = 1;
qtr(mo>3&mo<=6) = 2;
qtr(mo>6&mo<=9) = 3;
qtr(mo>9)       = 4;

% Drop negatives
saleq(saleq<=0)   = nan;
ebitda(ebitda<=0) = nan;
niq(niq<=0)       = nan;
piq(piq<=0)       = nan;

% Shift report quarter ahead of dataqtr by 1 qtr
repqtr          = yr*100 + qtr + 1;
repqtr(qtr==4)  = (yr(qtr==4)+1)*100 + 1;
clear datadate qtr mo yr

% Remove duplicates
[list, ix] = unique([permno repqtr],'rows');
permno    = list(:,1);
repqtr    = list(:,2);
saleq     = saleq(ix);
piq       = piq(ix);
niq       = niq(ix);
ebitda    = ebitda(ix);
clear list ix

% Build growth variables (year-on-year)
qtrlist   = unique(repqtr);
permlist  = unique(permno);
T         = length(qtrlist);
N         = length(permlist);

SA        = nan(T,N);
PI        = nan(T,N);
NI        = nan(T,N);
EB        = nan(T,N);
logSgr    = nan(T,N);
Sgr       = nan(T,N);
logPgr    = nan(T,N);
Pgr       = nan(T,N);
logEgr    = nan(T,N);
Egr       = nan(T,N);
logNgr    = nan(T,N);
Ngr       = nan(T,N);
for i=1:length(permlist)
    clear sa eb n p logsgr logegr logpgr logngr sgr egr pgr ngr
    
    loc  = find(permno==permlist(i));
    
    if length(loc)<=4, continue, end

    % Get qtr obs on exact qtr list so that lags will be accurate
    fi                   = find(qtrlist==repqtr(loc(1)));
    la                   = find(qtrlist==repqtr(loc(end)));
    loc1                 = (fi:la)';
    
    [~,ix1,ix2]          = intersect(qtrlist(loc1),repqtr(loc));

    % Sales
    logsa                = nan(size(loc1));
    sa                   = nan(size(loc1));
    logsa(ix1)           = log(saleq(loc(ix2)));
    sa(ix1)              = saleq(loc(ix2));
    
    logsgr               = logsa - lagmatrix( logsa , 4);
    sgr                  = sa./lagmatrix( sa , 4) - 1;
    SA(loc1(ix1),i)      = sa(ix1);
    logSgr(loc1(ix1),i)  = logsgr(ix1);
    Sgr(loc1(ix1),i)     = sgr(ix1);

    % EBITDA
    logeb                = nan(size(loc1));
    eb                   = nan(size(loc1));
    logeb(ix1)           = log(ebitda(loc(ix2)));
    eb(ix1)              = ebitda(loc(ix2));
    
    logegr               = logeb - lagmatrix( logeb , 4);
    egr                  = eb./lagmatrix( eb , 4) - 1;
    EB(loc1(ix1),i)      = eb(ix1);
    logEgr(loc1(ix1),i)  = logegr(ix1);
    Egr(loc1(ix1),i)     = egr(ix1);

    % Pretax Income
    logp                 = nan(size(loc1));
    p                    = nan(size(loc1));
    logp(ix1)            = log(piq(loc(ix2)));
    p(ix1)               = piq(loc(ix2));
    
    logpgr               = logp - lagmatrix( logp , 4);
    pgr                  = p./lagmatrix( p , 4) - 1;
    PI(loc1(ix1),i)      = p(ix1);
    logPgr(loc1(ix1),i)  = logpgr(ix1);
    Pgr(loc1(ix1),i)     = pgr(ix1);

    % Net Income
    logn                 = nan(size(loc1));
    n                    = nan(size(loc1));
    logn(ix1)            = log(niq(loc(ix2)));
    n(ix1)               = niq(loc(ix2));
    
    logngr               = logn - lagmatrix( logn , 4);
    ngr                  = n./lagmatrix( n , 4) - 1;
    NI(loc1(ix1),i)      = n(ix1);
    logNgr(loc1(ix1),i)  = logngr(ix1);
    Ngr(loc1(ix1),i)     = ngr(ix1);
    
    
    if floor(i/1000)*1000==i, i, end   
end
clear piq saleq ebitda niq logpiq logsaleq logebitda logniq logn logp logsa logeb fi la
clear sa eb n p logsgr logegr logpgr logngr sgr egr pgr ngr loc* i permno repqtr ix*
save('../output/CleanData/Income and Sales Qtrly All Firms through 2016 YOY.mat')
clear

