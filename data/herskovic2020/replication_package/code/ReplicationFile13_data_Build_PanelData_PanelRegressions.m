clear, addpath(genpath('functions\'))

%**************************************************************************
% Load Data
%**************************************************************************

load('../output/CleanData/aggregated_linkage_data_July2017');           % generated by "ReplicationFile12_data_Linkage_Data_Analysis.m"
load('../output/CleanData/Cashflow_matrix_annual_1925_2016_July2017');  % generated by "ReplicationFile10_data_Build_Cash_Flow_Growth_Data.m"
load('../output/CleanData/AT_BE_matrix_annual_1926_2016_July2017');     % generated by "ReplicationFile09_data_Build_Matrices_PanelRegressions.m"
load('../output/CleanData/EMP_AGE_matrix_annual_1925_2016_July2017');   % generated by "ReplicationFile11_data_Build_Employees_and_Age_Data.m"
load('../output/CleanData/DT_RD_IND_matrix_annual_1926_2016_July2017'); % generated by "ReplicationFile09_data_Build_Matrices_PanelRegressions.m"
load('../output/CleanData/ALL DATA MERGED July2017')                    % generated by 'ReplicationFile06_data_MergeDatasets.m'

permlist = ALL.permlist;
ME       = ALL.ME;
RV       = ALL.STOCKVOL1Y;
clear ALL

yrlist = (1926:2016)';

%**************************************************************************
% Deflator
%**************************************************************************
deflator_type = 'cpiUrb';

deflator.year = (1947:2016)';
aux = xlsread('../data/fred_deflators_annual.xlsx','B15:E84');
deflator.cpiUrb = aux(:,1);
deflator.pceAll = aux(:,2);
deflator.pceExclFoodEnergy = aux(:,3);
deflator.gdpDef = aux(:,4);

eval(['deflator.use = deflator.' char(deflator_type) ';'])
deflator.use_lag  = lagmatrix(deflator.use,1);

[locA,locB] = ismember(deflator.year,yrlist);
dflt = nan(size(yrlist));
dflt(locB(locA)) = 1 ./ (deflator.use(locA) / 100);

clear deflator



[T N] = size(RV);

infadj = dflt;

MEadj = ME .* kron(infadj,ones(1,size(ME,2)));
ATadj = AT .* kron(infadj,ones(1,size(AT,2)));
SAadj = SA .* kron(infadj,ones(1,size(AT,2)));
PIadj = PI .* kron(infadj,ones(1,size(AT,2)));
EBadj = EB .* kron(infadj,ones(1,size(AT,2)));
NIadj = NI .* kron(infadj,ones(1,size(AT,2)));
DTadj = DT .* kron(infadj,ones(1,size(DT,2)));
RDadj = RD .* kron(infadj,ones(1,size(RD,2)));


% Build concentration data
vec = @(x) reshape(x,[],1);
IND = floor(IND/100);
giclist = unique(vec(IND(~isnan(IND))));
HH = nan(T,N);

for t=1:T
    for i=1:length(giclist)
        loc = find(IND(t,:)==giclist(i));
        if isempty(loc), continue, end
        hh = nansum(SAadj(t,loc).^2)/nansum(SAadj(t,loc)).^2;
        HH(t,loc) = sqrt(hh);
    end
end

% Build herfindahl dataset from linkages
HERFIN  = nan(T,N);
HERFOUT = nan(T,N);
for t=1:T
    loc = find(yearin==yrlist(t));
    if ~isempty(loc)
        [~,ix1,ix2] = intersect(permlist,listin(loc));
        HERFIN(t,ix1) = herfin(loc(ix2));
    end
    loc = find(yearout==yrlist(t));
    if ~isempty(loc)
        [~,ix1,ix2] = intersect(permlist,listout(loc));
        HERFOUT(t,ix1) = herfout(loc(ix2));
    end
end
clear herf*

K   = MEadj./kron(nanmean(MEadj,2),ones(1,size(ME,2)));
KAT = ATadj./kron(nanmean(ATadj,2),ones(1,size(AT,2)));
KSA = SAadj./kron(nanmean(SAadj,2),ones(1,size(SA,2)));

paneldata = [   kron(ones(size(AT,2),1),yrlist)  ... % 1 - dates
                kron(permlist,ones(size(AT,1),1))  ... % 2 - permno
                vec(log(RV)) ...% 3 - logrv
                vec(log(K)) ...% 4 - logK
                vec(log(KAT)) ...% 5 - logKAT
                vec(log(KSA)) ...% 6 - logKSA
                vec(lagmatrix( log(K) ,1)) ...% 7 - laglogK
                vec(lagmatrix( log(KAT) ,1)) ...% 8 - laglogKAT
                vec(lagmatrix( log(KSA) ,1)) ...% 9 - laglogKSA
                vec(log(AGE)) ...% 10 - logage
                vec(DTadj./ATadj) ...% 11 - leverage
                vec(HH) ...% 12 - concent
                vec(RDadj./SAadj) ...% 13 - rdfrac
                vec(IND) ...% 14 - industry
                vec(HERFOUT)...% 15 - herfout
                vec(HERFIN)...% 16 - herfin
                vec(log(MEadj)) ...% 17 - 
                vec(log(ATadj)) ...% 18 - 
                vec(log(SAadj)) ...% 19 - 
                vec(lagmatrix( log(MEadj) ,1)) ...% 20 - 
                vec(lagmatrix( log(ATadj) ,1)) ...% 21 - 
                vec(lagmatrix( log(SAadj) ,1))]; % 22 - 

% Saving Panel Data as tab-delimited txt file
tic
delete('../output/CleanData/paneldata_July2017.txt')
fid = fopen('../output/CleanData/paneldata_July2017.txt','wt');
for k=1:length(paneldata(:,1))
    fprintf(fid,'%.0f\t%.0f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\t%.4f\n',paneldata(k,:));
end
fclose(fid);
toc

