clear, addpath(genpath('functions\'))

tic
pct     = [5 10 25 50 75 90 95];
% Only obs with network data, starting in 1980
% Size definition for TOP 1000 'ME' or 'SALES'
szdef   = 'SALES';

%**************************************************************************
% Data
%**************************************************************************
load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
DATA = ALL;
% Zeta regression
logmeannum  = log(nanmean(DATA.CUSTNUM,2));
logtotnum   = log(sum(~isnan(DATA.SALES),2));
logtotnum(isnan(logmeannum)) = nan;
stats       = regstats(logmeannum,logtotnum,'linear','tstat'); 
zeta        = stats.tstat.beta(2)
tzeta       = stats.tstat.t(2)

% All other analysis
if strcmp(szdef,'ME')
    DATA.SZ     = DATA.ME;
elseif strcmp(szdef,'SALES')
    DATA.SZ     = DATA.SALES;
end
DATA.SZlag   = lagmatrix(DATA.SZ,1);
T           = length(DATA.yrlist);
DATA.VARSTK  = DATA.STOCKVOL1Y.^2;
DATA.VARSAL  = DATA.SALESVOL1Y.^2;
DATA.VARSTKnxt  = lagmatrix(DATA.VARSTK,-1);
DATA.VARSALnxt  = lagmatrix(DATA.VARSAL,-1);

DATA.SZGR    = log(DATA.SZ./lagmatrix(DATA.SZ,1));
DATA         = rmfield(DATA,{'SALES','ME','SALESVOL1Y','SALESVOL5Y','STOCKVOL1Y'});


% Limit to 1980-2013 sample
fld     = setdiff(fields(DATA),[{'permlist'}]);
loc     = find(DATA.yrlist >= 1980 & DATA.yrlist <= 2012);
for i=1:length(fld)
    eval(['DATA.' char(fld(i)) ' = DATA.' char(fld(i)) '(loc,:);'])
end
T       = length(loc);
clear loc thous rk t i fld

% Limit to observations with non-missing out-herfindahls
fld     = setdiff(fields(DATA),[{'yrlist','permlist'}]);
loc     = find(~isnan(DATA.CUSTHERF) | ~isnan(DATA.SUPPHERF) | ~isnan(DATA.CUSTNUM) | ~isnan(DATA.SUPPNUM));
badloc  = setdiff(1:numel(DATA.CUSTHERF),loc);
for i=1:length(fld)
    eval(['DATA.' char(fld(i)) '(badloc) = nan;'])
end
clear loc thous rk t i fld

N_byType = [sum(DATA.CUSTNUM >= 1,2), sum(DATA.SUPPNUM >= 1,2), sum(DATA.CUSTNUM >= 1 | DATA.SUPPNUM >= 1,2)];
N_posSAL = sum( DATA.SZ >= 0,2);
Shares_byType = bsxfun(@times, N_byType, 1 ./ N_posSAL);

 
%**************************************************************************
% Bootstrap
%**************************************************************************

rng(467); % lucky number :)
TS_NumberNetworkFirms = N_byType(:,3);
N_NetworkFirms = floor(nanmean(N_byType(:,3)));
K_bootstrap    = 100;
BST = nan(N_NetworkFirms * K_bootstrap, T);
for t = 1:T
    loc_net = find(DATA.CUSTNUM(t,:)' >= 1 | DATA.SUPPNUM(t,:)' >= 1);
    loc_bst = randsample(loc_net,N_NetworkFirms * K_bootstrap,true);
    BST(:,t) = loc_bst;
end

bootstrap = false; % true vs. false


%**************************************************************************
% Deflator
%**************************************************************************
deflator_type = 'cpiUrb'

deflator.year = (1947:2016)';
aux = xlsread('../data/fred_deflators_annual.xlsx','B15:E84');
deflator.cpiUrb = aux(:,1);
deflator.pceAll = aux(:,2);
deflator.pceExclFoodEnergy = aux(:,3);
deflator.gdpDef = aux(:,4);

eval(['deflator.use = deflator.' char(deflator_type) ';'])
deflator.use_lag  = lagmatrix(deflator.use,1);

[locA,locB] = ismember(deflator.year,DATA.yrlist);
dflt = nan(size(DATA.yrlist));
dflt(locB(locA)) = 1 ./ (deflator.use(locA) / 100);

dflt_lag = nan(size(DATA.yrlist));
dflt_lag(locB(locA)) = 1 ./ (deflator.use_lag(locA) / 100);


DATA.SZDEF     = bsxfun(@times, DATA.SZ, dflt);
DATA.SZDEFlag  = bsxfun(@times, DATA.SZlag, dflt_lag);

DATA.SZ     = DATA.SZDEF;
DATA.SZlag  = DATA.SZDEFlag;
clear deflator dflt

close all
%**************************************************************************
% Size distribution table
%**************************************************************************

% Moments:
%    1.  TS avg of XS avg of log(Size)
%    2.  TS avg of XS std of log(Size)
%    3.  TS avg of XS percentiles of log(Size)

X = log(DATA.SZ);
gr= DATA.SZGR;

szdistn_avg = nan(T,9);

for t=1:T
        tmp = X(t,:);
        szdistn_avg(t,:)    = [nanmean(tmp) nanstd(tmp) prctile(tmp,pct)];
        grdisp_avg(t,:)     = nanstd(gr(t,:));
end
SZmom        = nanmean(szdistn_avg)';
   
SZmom_non_btr = szdistn_avg';

%**************************************************************************
% Stock Vol distribution table
%**************************************************************************

% Moments (using variance of stock returns):
%    1.  TS avg of XS avg of log(Variance)
%    2.  TS avg of XS std of log(Variance)
%    3.  TS avg of XS percentiles of log(Variance)
%    4.  TS avg of XS correlation between log(Variance) at t+1 and log(Size) at t

%X   = log(DATA.VARSTK);
%Y   = log(DATA.SZlag);

X   = log(DATA.VARSTKnxt);
Y   = log(DATA.SZ);

voldistn_avg = nan(T,9);
grdisp_avg   = nan(T,1);

for t=1:T
        tmp = X(t,:);
        voldistn_avg(t,:)    = [nanmean(tmp) nanstd(tmp) prctile(tmp,pct)];
end
VOLSTKmom = nanmean(voldistn_avg)';

corrxy_avg = nan(T,1);
for t=1:T
    if sum(~isnan(X(t,:)'+Y(t,:)'))<100, continue, end
        C           = corr([X(t,:)',Y(t,:)'],'rows','pairwise');
        corrxy_avg(t,:) = C(1,2);
end
VOLSTKmom  = [VOLSTKmom ; nanmean(corrxy_avg)]; 

VOLSTKmom_non_btr = [voldistn_avg, corrxy_avg]';

%**************************************************************************
% SALES Vol distribution table
%**************************************************************************

% Moments (using variance of sales):
%    1.  TS avg of XS avg of log(Variance)
%    2.  TS avg of XS std of log(Variance)
%    3.  TS avg of XS percentiles of log(Variance)
%    4.  TS avg of XS correlation between log(Variance) at t+1 and log(Size) at t

X   = log(DATA.VARSALnxt);
Y   = log(DATA.SZ);

agg = nansum(DATA.SZGR.*lagmatrix(DATA.SZ,1),2)./nansum(lagmatrix(DATA.SZ,1),2);

voldistn_avg = nan(T,9);
for t=1:T
        tmp = X(t,:);
        voldistn_avg(t,:)  = [nanmean(tmp) nanstd(tmp) prctile(tmp,pct)];
end
VOLSALmom = nanmean(voldistn_avg)';

corrxy_avg = nan(T,1);
for t=1:T
    
    if sum(~isnan(X(t,:)'+Y(t,:)'))<100, continue, end
        C           = corr([X(t,:)',Y(t,:)'],'rows','pairwise');
        corrxy_avg(t,:) = C(1,2);
end
VOLSALmom  = [VOLSALmom ; nanmean(corrxy_avg)];


VOLSALmom_non_btr = [voldistn_avg, corrxy_avg]';

%**************************************************************************
% Network distribution table
%**************************************************************************

Nout  = nan(T,length(pct));
Hout  = nan(T,length(pct));
Nin   = nan(T,length(pct));
Hin   = nan(T,length(pct));

cNSout     = nan(T,1);
cHSout     = nan(T,1);
cNVSTKout  = nan(T,1);
cNVSALout  = nan(T,1);

cNSin      = nan(T,1);
cHSin      = nan(T,1);
cNVSTKin   = nan(T,1);
cNVSALin   = nan(T,1);
cHVSTKout  = nan(T,1);
cHVSALout  = nan(T,1);
cHVSTKin   = nan(T,1);
cHVSALin   = nan(T,1);

for t=1:T
    if DATA.yrlist(t)<1980, continue, end
        Nout(t,:) = prctile(DATA.CUSTNUM(t,:),pct);
        Nin(t,:)  = prctile(DATA.SUPPNUM(t,:),pct);
        Hin(t,:)    = prctile(DATA.SUPPHERF(t,:),pct);
        Hout(t,:)   = prctile(DATA.CUSTHERF(t,:),pct);
        
        C = corr(log([DATA.CUSTNUM(t,:)',DATA.SZ(t,:)']),'rows','pairwise');
        cNSout(t)   = C(1,2);
        C = corr(log([DATA.CUSTHERF(t,:)',DATA.SZ(t,:)']),'rows','pairwise');
        cHSout(t)   = C(1,2);
        C = corr(log([DATA.SUPPNUM(t,:)',DATA.SZ(t,:)']),'rows','pairwise');
        cNSin(t)    = C(1,2);
        C = corr(log([DATA.SUPPHERF(t,:)',DATA.SZ(t,:)']),'rows','pairwise');
        cHSin(t)    = C(1,2);
        if t<=T
            C = corr(log([DATA.CUSTHERF(t,:)',DATA.VARSTKnxt(t,:)']),'rows','pairwise'); 
            cHVSTKout(t)= C(1,2);
            C = corr(log([DATA.CUSTHERF(t,:)',DATA.VARSALnxt(t,:)']),'rows','pairwise');
            cHVSALout(t)= C(1,2);
            C = corr(log([DATA.SUPPHERF(t,:)',DATA.VARSTKnxt(t,:)']),'rows','pairwise');
            cHVSTKin(t) = C(1,2);
            C = corr(log([DATA.SUPPHERF(t,:)',DATA.VARSALnxt(t,:)']),'rows','pairwise');
            cHVSALin(t) = C(1,2);
        end
end

NETmom_non_btr = [Nout'; Hout'; cNSout'; cHSout'; cHVSALout'; Nin'; Hin'; cNSin'; cHSin'; cHVSALin'];   
    
table_NETmom = nanmean([Nout Hout cNSout cHSout cHVSALout Nin  Hin  cNSin  cHSin  cHVSALin])' ;       

MomentsToMatch.table_STK = [SZmom; VOLSTKmom(1:length(pct)+3); table_NETmom; N_NetworkFirms];

MomentsToMatch.table_SAL = [SZmom; VOLSALmom(1:length(pct)+3); table_NETmom; N_NetworkFirms];


DATA = [SZmom_non_btr; VOLSTKmom_non_btr; NETmom_non_btr; TS_NumberNetworkFirms'];
all_moments_avg = mean(DATA,2);
all_moments_cov = cov(DATA','partialrows');
MomentsToMatch.all_moments_avg = all_moments_avg;
MomentsToMatch.all_moments_cov = all_moments_cov;
MomentsToMatch.DATA            = DATA;
MomentsToMatch.T               = T;
save('../output/CleanData/MomentsToMatch_Jul2017.mat','MomentsToMatch');

