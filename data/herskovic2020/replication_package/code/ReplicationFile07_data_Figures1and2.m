%
stdize = @(x) (x - nanmean(x)) ./ nanstd(x);

% Use variance
ALL.STOCKVOL1Y = ALL.STOCKVOL1Y .^ 2;
ALL.SALESVOL1Y = ALL.SALESVOL1Y .^ 2;


%**************************************************************************
% Figure 1, panel a
%**************************************************************************

% Dispersion in size and average volatility
y1 = nanmean(log(ALL.STOCKVOL1Y),2);
y2 = nanstd(log(ALL.ME),[],2); y2 = lagmatrix(y2,1);
h=figure('Color',[1 1 1]);
plot1 = plot((1:length(y2))',stdize(y2),'-k',(1:length(y1))',stdize(y1),'--r','linewidth',2);
set(gca,'fontname','timesnewroman','fontsize',20,'xtick',find(ismember(ALL.yrlist,[1930:10:2010]')),'xticklabel',num2str([1930:10:2010]'),...
    'ylim',[-2.5,3],'ytick',[-2:3])
set(plot1(2),'Displayname','Mean log vol. (market)')
set(plot1(1),'Displayname','Lagged Size dispersion (market)')
legend('location','southeast')
legend boxoff
xlim([0 92])
f = ['../figures/Fig1a.eps'];
export_fig(f)

