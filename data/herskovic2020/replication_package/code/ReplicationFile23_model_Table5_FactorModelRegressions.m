clear, addpath(genpath('functions\'))

load('../output/CleanData/ALL DATA MERGED July2017')                    % generated by 'ReplicationFile06_data_MergeDatasets.m'
T = length(ALL.yrlist);

loc                 = isnan(ALL.STOCKVOL1Y+ALL.ME);  % full sample
ALL.STOCKVOL1Y(loc) = nan;
ALL.ME(loc)         = nan;

muvolfull   = nanmean(log(ALL.STOCKVOL1Y),2);
sigvolfull  = nanstd(log(ALL.STOCKVOL1Y),[],2);
sigSfull    = nanstd(log(ALL.ME),[],2);


%**************************************************************************
% Deflator
%**************************************************************************
deflator_type = 'cpiUrb';

deflator.year = (1947:2016)';
aux = xlsread('../data/fred_deflators_annual.xlsx','B15:E84');
deflator.cpiUrb = aux(:,1);
deflator.pceAll = aux(:,2);
deflator.pceExclFoodEnergy = aux(:,3);
deflator.gdpDef = aux(:,4);

eval(['deflator.use = deflator.' char(deflator_type) ';'])
deflator.use_lag  = lagmatrix(deflator.use,1);

[locA,locB] = ismember(deflator.year,ALL.yrlist);
dflt = nan(size(ALL.yrlist));
dflt(locB(locA)) = 1 ./ (deflator.use(locA) / 100);

clear deflator

ALL.ME_dflt    = bsxfun(@times, ALL.ME, dflt);




%**************************************************************************
% 
%**************************************************************************
[~,N] = size(ALL.STOCKVOL1Y);

BETAS = nan(N,3);
R2    = nan(N,3);
for i = 1:N

    if sum(~isnan(log(ALL.STOCKVOL1Y(:,i)))) >= 25
    reg_result = regstats(log(ALL.STOCKVOL1Y(:,i)),lagmatrix(sigSfull,1), 'linear',{'beta','rsquare'}); b1 = reg_result.beta(2); r1 = reg_result.rsquare * 100;
    reg_result = regstats(log(ALL.STOCKVOL1Y(:,i)),lagmatrix(muvolfull,1),'linear',{'beta','rsquare'}); b2 = reg_result.beta(2); r2 = reg_result.rsquare * 100;
    reg_result = regstats(log(ALL.STOCKVOL1Y(:,i)),muvolfull,           'linear',{'beta','rsquare'}); b3 = reg_result.beta(2); r3 = reg_result.rsquare * 100;

    BETAS(i,:) = [b1 b2 b3];
    R2(i,:)    = [r1 r2 r3];
    end
end

loc  = find(~isnan(sum(BETAS,2)));
loc1 = loc(nanmean(ALL.ME_dflt(:,loc)) < prctile(nanmean(ALL.ME_dflt(:,loc)),20));
loc5 = loc(nanmean(ALL.ME_dflt(:,loc)) >= prctile(nanmean(ALL.ME_dflt(:,loc)),80));
disp('Min 25 yrs of data (obs)')
disp('Panel A')
disp([nanmean(BETAS); nanmean(BETAS(loc1,:)); nanmean(BETAS(loc5,:))])
disp('Panel B')
disp([nanmean(R2); nanmean(R2(loc1,:)); nanmean(R2(loc5,:))])


tab_data = [{'All firms'} cellstr(num2str(nanmean(BETAS)','$%.2f$   '))';...
       {'\ \ \ Q1'}  cellstr(num2str(nanmean(BETAS(loc1,:))','$%.2f$   '))';...
       {'\ \ \ Q5'}  cellstr(num2str(nanmean(BETAS(loc5,:))','$%.2f$   '))';...
       {'All firms'} cellstr(num2str(nanmean(R2)','$%.2f$   '))';...
       {'\ \ \ Q1'}  cellstr(num2str(nanmean(R2(loc1,:))','$%.2f$   '))';...
       {'\ \ \ Q5'}  cellstr(num2str(nanmean(R2(loc5,:))','$%.2f$   '))'];


%**************************************************************************
%
%  Model
%
%**************************************************************************

T = 33;
N = 1332;
muvolfull   = nan(T,1);
sigSfull    = nan(T,1);
muvol       = nan(T,N);
muS       = nan(T,N);

Table_Stats_Model = [];

for t = 1:33;
    load(['../output/TSFit_Results/TSFit_',num2str(t,'%.0f'),'.mat'],'estimation') % generated by "ReplicationFile22_model_TS_ModelFit.m"
    Model_Output = estimation.Model_Output;

    Sim_data_S       = nanmean(log(Model_Output.Sim_data_S),2);
    Sim_data_sig     = nanmean(Model_Output.Sim_data_sig,2);

    % All public firms
    muvolfull(t)   = nanmean(Sim_data_sig);
    sigSfull(t)    = nanstd(Sim_data_S);

    loc1 = find(Sim_data_S <  prctile(Sim_data_S,20));
    loc5 = find(Sim_data_S >= prctile(Sim_data_S,80));

    muvol(t,:) = Sim_data_sig;
    muS(t,:) = Sim_data_S;

end 


BETAS = nan(N,3);
R2    = nan(N,3);
for i = 1:N

    if sum(~isnan(log(ALL.STOCKVOL1Y(:,i)))) >= 25
    reg_result = regstats(muvol(:,i),lagmatrix(sigSfull,1), 'linear',{'beta','rsquare'}); b1 = reg_result.beta(2); r1 = reg_result.rsquare * 100;
    reg_result = regstats(muvol(:,i),lagmatrix(muvolfull,1),'linear',{'beta','rsquare'}); b2 = reg_result.beta(2); r2 = reg_result.rsquare * 100;
    reg_result = regstats(muvol(:,i),muvolfull,           'linear',{'beta','rsquare'}); b3 = reg_result.beta(2); r3 = reg_result.rsquare * 100;

    BETAS(i,:) = [b1 b2 b3];
    R2(i,:)    = [r1 r2 r3];
    end
end


disp(' MODEL ')
loc  = find(~isnan(sum(BETAS,2)));
loc1 = loc(nanmean(muS(:,loc)) < prctile(nanmean(muS(:,loc)),20));
loc5 = loc(nanmean(muS(:,loc)) >= prctile(nanmean(muS(:,loc)),80));
disp('Min 25 yrs of data (obs)')
disp('Panel A')
disp([nanmean(BETAS); nanmean(BETAS(loc1,:)); nanmean(BETAS(loc5,:))])
disp('Panel B')
disp([nanmean(R2); nanmean(R2(loc1,:)); nanmean(R2(loc5,:))])


tab_model = [ cellstr(num2str(nanmean(BETAS)','$%.2f$   '))';...
              cellstr(num2str(nanmean(BETAS(loc1,:))','$%.2f$   '))';...
              cellstr(num2str(nanmean(BETAS(loc5,:))','$%.2f$   '))';...
              cellstr(num2str(nanmean(R2)','$%.2f$   '))';...
              cellstr(num2str(nanmean(R2(loc1,:))','$%.2f$   '))';...
              cellstr(num2str(nanmean(R2(loc5,:))','$%.2f$   '))'];

tab = [tab_data, repmat({''},6,1) tab_model];

