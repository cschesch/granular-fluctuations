clear, addpath(genpath('functions\'))

for k = 1:4
switch k
    case 1, truncation = true;  decomp = 1; % 1. Benchmark Result with truncation
    case 2, truncation = false; decomp = 1; % 1. Benchmark Result without truncation
    case 3, truncation = true;  decomp = 2; % 2. No network effects
    case 4, truncation = true;  decomp = 3; % 3. No internal diversification effects
end
                                      
N     = 5000; % Number of firms (default: 5000)
nloop = 100;  % Number of bootstrap draws (default: 100)


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   CALIBRATION FOR: 
%        sig = sig0*ones(N,1) + sig1*log(1 + exp(mu_So)./S);
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Load estimated parameters
load('../output/EstimationResults/theta_bm.mat')        % generated by "ReplicationFile19_model_smm_and_hessian.m"
X    = estimation.theta_hat(1:7)';
Ntop = estimation.theta_hat(8);

switch decomp
    case 2 % no network effects
        X(1) = 0; % gamma = 0
    case 3 % no internal diversification -- sig1 = 0, and sig0 keeps the median sigma_i unchanged
        X(2) = X(2) + X(3)*log(2) ; % sig0 --- fundamental shock vol (sigma_epsilon)
        X(3) = 0; % sig1 --- governs internal diversification effect (lambda)
end


if truncation
    w_tr = 0.1;
else
    w_tr = 0;
    Ntop = N;
end

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Creating moments functions: g   (K by 1)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Moments to exclude: 
loc_exclude = []; % target all moments

theta_0 = [X, Ntop]';   
M = length(theta_0);
load('../output/CleanData/MomentsToMatch_Jul2017.mat'); % generated by "ReplicationFile15_data_MomentsToCalibrate.m"
all_moments_cov  = MomentsToMatch.all_moments_cov;
all_moments_avg  = MomentsToMatch.all_moments_avg;

all_moments_cov_NormX  = cov(NormX(MomentsToMatch.DATA)','partialrows');
all_moments_avg_NormX  = mean(NormX(MomentsToMatch.DATA),2);
T                = MomentsToMatch.T;

data_moments = all_moments_avg;
data_moments(loc_exclude) = [];
K = length(NormX(data_moments));

g     = @(theta) nanmean( bsxfun(@plus, NormX(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude,w_tr)), - all_moments_avg_NormX),2);
g_tab = @(theta) bsxfun(@plus,  NormX(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude,w_tr)), -  all_moments_avg_NormX);

compute_model_moments = @(theta) nanmean(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude,w_tr),2);
compute_model_momentsNormX = @(theta) nanmean(NormX(simulate_model(theta(1:7),N,theta(8),nloop,loc_exclude,w_tr)),2);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Saving Model results (Table of moments)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

x0 =  theta2x(theta_0,N);
W = eye(K);
W = W / mean(diag(W));

% Testing x functions
x_test = max(abs([theta_0 - x2theta(theta2x(theta_0,N),N)]));
if x_test > 1e-14, disp('WARNING!  theta2x and x2theta function are not consistent'), end

% Run estimation to get FVAL
if truncation
    disp('SMM Function')
    tic
    FVAL_guess = smm_gWg(x0,W,N,nloop,all_moments_avg_NormX,loc_exclude)
    disp([num2str((toc/60),'%.2f'),' minutes'])
else
    FVAL_guess = nan;
end

theta_guess    = theta_0;
[model_moments_guess_full_table, ~, ~, CorrWS, Model_Output] = simulate_model(theta_guess(1:7),N,theta_guess(8),nloop,[],w_tr);
model_moments_guess = nanmean(model_moments_guess_full_table,2);
model_moments_guess_NormX = nanmean(NormX(model_moments_guess_full_table),2);

estimation.Model_Output        = Model_Output;
estimation.model_moments_guess = model_moments_guess;
estimation.model_moments_guess_NormX = model_moments_guess_NormX;
estimation.data_moments        = MomentsToMatch.all_moments_avg;
estimation.data_moments_NormX  = NormX(MomentsToMatch.all_moments_avg);
estimation.FVAL_guess          = FVAL_guess;
estimation.theta_guess         = theta_guess;
estimation.loc_exclude         = loc_exclude;
estimation.AvgCorrWS           = nanmean(CorrWS);
if truncation
save(['../output/EstimationResults/decomp_',num2str(decomp,'%.0f'),'.mat'],'estimation')
else
save(['../output/EstimationResults/decomp_NoTruncation_',num2str(decomp,'%.0f'),'.mat'],'estimation')
end
end



