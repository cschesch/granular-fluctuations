clear, addpath(genpath('functions/'))

N     = 5000; % Number of firms (default: 5000)
nloop = 100;  % Number of bootstrap draws (default: 100)

% Weighting Matrix
for sigtype = [2 3]

% Runn smm?
run_smm = false; % Set to false to only run the benchmark calibration
                 % The guess saved in 'guess/AltSigmaModel_parameters.mat' folder is the solution to the smm estimation 

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   INITIAL GUESS -- solution from the optimization
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

switch sigtype
    case 2
        load('../output/EstimationResults/theta_bm.mat')        % generated by "ReplicationFile19_model_smm_and_hessian.m"
        theta_0 = estimation.theta_hat; clear estimation
        theta_0(2) = 6.66; % kappa = 6.66 --- sigma_{epsilon,i} = kappa S_i^alpha
        theta_0(3) = 0.15; % alpha = 0.15 --- sigma_{epsilon,i} = kappa S_i^alpha
    case 3
        load('guess/AltSigmaModel_parameters.mat')
        theta_0 = AltSigmaModel_parameters(1:8);
end


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Creating moments functions: g   (K by 1)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

% Moments to exclude: 
loc_exclude = []; % target all moments

M = length(theta_0);
load('../output/CleanData/MomentsToMatch_Jul2017.mat'); % generated by "ReplicationFile15_data_MomentsToCalibrate.m"
all_moments_cov  = MomentsToMatch.all_moments_cov;
all_moments_avg  = MomentsToMatch.all_moments_avg;

all_moments_cov_NormX  = cov(NormX(MomentsToMatch.DATA)','partialrows');
all_moments_avg_NormX  = mean(NormX(MomentsToMatch.DATA),2);
T                = MomentsToMatch.T;

data_moments = all_moments_avg;
data_moments(loc_exclude) = [];
K = length(NormX(data_moments));

g     = @(theta) nanmean( bsxfun(@plus, NormX(simulate_model_alt_sig(theta(1:7),N,theta(8),nloop,loc_exclude,sigtype)), - all_moments_avg_NormX),2);
g_tab = @(theta) bsxfun(@plus,  NormX(simulate_model_alt_sig(theta(1:7),N,theta(8),nloop,loc_exclude,sigtype)), -  all_moments_avg_NormX);

compute_model_moments = @(theta) nanmean(simulate_model_alt_sig(theta(1:7),N,theta(8),nloop,loc_exclude,sigtype),2);
compute_model_momentsNormX = @(theta) nanmean(NormX(simulate_model_alt_sig(theta(1:7),N,theta(8),nloop,loc_exclude,sigtype)),2);


%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Weighting Matrix: W
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
all_moments_cov(loc_exclude,:) = [];
all_moments_cov(:,loc_exclude) = [];

W = eye(K);

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   SMM
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

disp('SMM')
disp('  ')

% Initial guess
x0 =  theta2x(theta_0,N);

% Testing x functions
x_test = max(abs([theta_0 - x2theta(theta2x(theta_0,N),N)]));
if x_test > 1e-14, disp('WARNING!  theta2x and x2theta function are not consistent'), ascasc, end

% Run estimation a few times:
disp('SMM: Testing the Function')
tic
FVAL_guess = smm_gWg_alt_sig(x0,W,N,nloop,all_moments_avg_NormX,loc_exclude,sigtype)
disp([num2str((toc/60),'%.2f'),' minutes'])

theta_guess    = x2theta(x0,N);
model_moments_guess_full_table = simulate_model_alt_sig(theta_guess(1:7),N,theta_guess(8),nloop,[],sigtype);
model_moments_guess = nanmean(model_moments_guess_full_table,2);
model_moments_guess_NormX = nanmean(NormX(model_moments_guess_full_table),2);

if run_smm && (sigtype == 3)
    disp('SMM: Solving Minimization')
    tic
    options = optimset('TolX',1e-4,'TolFun',1e-4,'Display','iter');

    [x_hat,FVAL,EXITFLAG] = fminsearch(@(x) smm_gWg_alt_sig(x,W,N,nloop,all_moments_avg_NormX,loc_exclude,sigtype), x0, options)
    disp([num2str((toc/60),'%.2f'),' minutes'])
else
    x_hat = x0;
    FVAL  = FVAL_guess;
    EXITFLAG = nan;
end

% Estimated parameters
theta_hat    = x2theta(x_hat,N);

disp('SMM: theta_0 and theta_hat')
disp(num2str([theta_0 theta_hat],'%.4f   '))

model_moments_full_table = model_moments_guess_full_table;% + nan;

model_moments = nanmean(model_moments_full_table,2);
model_moments_NormX = nanmean(NormX(model_moments_full_table),2);

table_moments_full = [model_moments, MomentsToMatch.all_moments_avg];

estimation.W                   = W;
estimation.model_moments_guess = model_moments_guess;
estimation.model_moments_guess_NormX = model_moments_guess_NormX;
estimation.model_moments_NormX = model_moments_NormX;
estimation.model_moments       = model_moments;
estimation.data_moments        = MomentsToMatch.all_moments_avg;
estimation.data_moments_NormX  = NormX(MomentsToMatch.all_moments_avg);
estimation.EXITFLAG            = EXITFLAG;
estimation.FVAL                = FVAL;
estimation.FVAL_guess          = FVAL_guess;
estimation.theta_guess         = theta_guess;
estimation.theta_hat           = theta_hat;
estimation.loc_exclude         = loc_exclude;
save(['../output/EstimationResults/theta_AltSig',num2str(sigtype,'%.0f'),'.mat'],'estimation')
x0 = x_hat;





%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%
%   Creating moments derivatives: G0 (K by M), where m = length(theta)
%                 G0(i,j) = d g(i) / d theta(j)
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

if sigtype == 3
    
theta_0 = estimation.theta_hat;

disp('Hessian')
disp('  ')
disp('Hessian: Calculating the variance covarince g')
tic
g_cov   = g_tab(theta_0); g_cov = g_cov * g_cov' / nloop;
disp([num2str((toc/60),'%.2f'),' minutes'])

g_0 = g(theta_0);

tic
for eps = [-1, 1]

    G0 = nan(K,M);

    for j = 1:M

        eps =  sign(eps) * theta_0(j) * 0.0100;
        
        if j == 8; eps = sign(eps); end
        
        theta_1    = theta_0;
        theta_1(j) = theta_0(j) + eps;
        g_1 = g(theta_1);
        G0(:,j) = (g_1 - g_0) ./ eps;
    end
    
    if eps<0
        G_neg = G0;
    else
        G_pos = G0;
    end
    
end    

disp([num2str(toc/60,'%.2f'),' minutes'])

hessian.G_neg          = G_neg;
hessian.G_pos          = G_pos;
hessian.g_cov          = g_cov;
hessian.theta_0        = theta_0;
hessian.nloop          = nloop;
hessian.T              = T;
save(['../output/EstimationResults/se_matrices_AltSig',num2str(sigtype,'%.0f'),'.mat'],'hessian')

end


end

