%**************************************************************************
% Build T x N Matrices of Annual Total Assets and Book Equity
%**************************************************************************
 
load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
permlist = ALL.permlist;
yrlist   = ALL.yrlist;
clear ALL

fid     = fopen('../data/Book value and assets annual data all firms through Dec 2016.txt');
data    = textscan(fid,'%*n%n%n%*n%*s%*s%*s%*s%*s%n%n%n%n%n%n%*s','headerlines',1,'delimiter','\t');

permno   = data{1};
datadate = data{2};
atq      = data{3}; % total assets
ceq      = data{4}; % common equity (book)
ceql     = data{5}; % common equity (liquidity value, book)
itcb     = data{6}; % inv tex ben
pstk     = data{7}; % preferred stock (book, total)
pstkl    = data{8}; % preferred stock (book, liq)

be      = ceq + (isnan(ceq)&~isnan(ceql)).*ceql + ~isnan(itcb).*itcb + ~isnan(pstk).*pstk  + (isnan(pstk)&~isnan(pstkl)).*pstkl;
clear ceq* pstk* itcb

yr = floor(datadate/10000);

T = length(yrlist);
N = length(permlist);

% yr(mo<=6) = yr(mo<=6)-1;
clear mo

AT = nan(T,N);
BE = nan(T,N);
for i=1:N
    loc  = find(permno==permlist(i));
    loc1 = find(ismember(yrlist,yr(loc)));
    
    if length(loc)>length(loc1), 
        [~,ix] = unique(yr(loc));
        AT(loc1,i) = atq(loc(ix));
        BE(loc1,i) = be(loc(ix));
    else    
        AT(loc1,i) = atq(loc);
        BE(loc1,i) = be(loc);
    end    
    if floor(i/1000)*1000==i, i, end
end

AT(AT<=0) = nan;
BE(BE<=0) = nan;
save('../output/CleanData/AT_BE_matrix_annual_1926_2016_July2017','AT','BE');
clear

%**************************************************************************
% Build T x N Matrices of Other Fundamentals
%**************************************************************************

load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
permlist = ALL.permlist;
yrlist   = ALL.yrlist;
clear ALL

fid     = fopen('../data/GIC Industry and Debt and R&D annual data all firms through 2016.txt');
data    = textscan(fid,'%*n%n%n%*n%*s%*s%*s%*s%*s%n%n%n%*s%n','headerlines',1,'delimiter','\t');


permno   = data{1};
datadate = data{2};
dlc      = data{3}; % debt in curr liabilities --- variable DLC
dlt      = data{4}; % total long term debt --- variable DLTT
rdx      = data{5}; % r&d expense --- variable XRD
gic      = data{6};  % GIC Industry (6 digit, 70 categories) --- variable GIND

dt      = nansum([dlt dlc],2);
clear dlt dlc

yr = floor(datadate/10000);

T = length(yrlist);
N = length(permlist);

% yr(mo<=6) = yr(mo<=6)-1;
clear mo

DT = nan(T,N);
RD = nan(T,N);
IND= nan(T,N);
for i=1:N
    loc  = find(permno==permlist(i));
    loc1 = find(ismember(yrlist,yr(loc)));
    
    if length(loc)>length(loc1), 
        [~,ix] = unique(yr(loc));
        DT(loc1,i) = dt(loc(ix));
        RD(loc1,i) = rdx(loc(ix));
        IND(loc1,i)= gic(loc(ix));
    else    
        DT(loc1,i) = dt(loc);
        RD(loc1,i) = rdx(loc);
        IND(loc1,i)= gic(loc);
    end    
    if floor(i/1000)*1000==i, i, end
end

DT(DT<=0)  = nan;
RD(RD<0)   = nan;
IND(IND<=0)= nan;
save('../output/CleanData/DT_RD_IND_matrix_annual_1926_2016_July2017','DT','RD','IND');
clear


