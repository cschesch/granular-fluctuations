tab_moments    = [];
tab_parameters = [];
tab_wald       = [];
tab_FVAL       = [];
for col = [1 2 3] % Column 1: SMM Estimation
                  % Column 2: Model without networks effects
                  % Column 3: Model without internal diversification
                  
% Loading benchmark SMM
switch col
    case 1
        load('../output/EstimationResults/theta_bm.mat')        % generated by "ReplicationFile19_model_smm_and_hessian.m"
        load('../output/EstimationResults/se_matrices_bm.mat')  % generated by "ReplicationFile19_model_smm_and_hessian.m"
        loc = ones(8,1) == 1;
    case 2
        load('../output/EstimationResults/theta_NoNetwork.mat')       % generated by "ReplicationFile26_smm_and_hessian_NoNetwork.m"
        load('../output/EstimationResults/se_matrices_NoNetwork.mat') % generated by "ReplicationFile26_smm_and_hessian_NoNetwork.m"
        loc = ones(8,1); loc(1) = 0; loc = loc == 1;
    case 3
        load('../output/EstimationResults/theta_NoID.mat')            % generated by "ReplicationFile27_smm_and_hessian_NoID.m"
        load('../output/EstimationResults/se_matrices_NoID.mat')      % generated by "ReplicationFile27_smm_and_hessian_NoID.m"
        loc = ones(8,1); loc(3) = 0; loc = loc == 1;
end
    theta = estimation.theta_hat;
    FVAL  = estimation.FVAL;

    loc_exclude            = estimation.loc_exclude;
    model_moments_NormX    = estimation.model_moments_NormX;
    data_moments_NormX     = estimation.data_moments_NormX;
    h_moments              = model_moments_NormX - data_moments_NormX;
    h_moments(loc_exclude) = [];


    G_neg          = hessian.G_neg(:,loc);
    G_pos          = hessian.G_pos(:,loc);

    W              = estimation.W;
    g_cov          = hessian.g_cov;
    nloop          = hessian.nloop;
    T              = hessian.T;


    tau = T/nloop;

    % s.e. of all parameters
    G0 = (G_neg + G_pos) * 0.5;
    A  = inv(G0' * W * G0);
    B  = G0' * W * g_cov * W' * G0;
    AsynCov   = (1 + tau) * A * B * A; % this is the asymptotic variance-covariance matrix of sqrt(T) * (theta_hat - theta_true)
    theta_cov = AsynCov / T;
    se = nan(8,1);
    se(loc) = sqrt(diag(theta_cov));

    % Wald test -- Standard GMM test - Testing correlation moments?
    loc_corr = [1:28];
    H = G0(loc_corr,:);
    h = h_moments(loc_corr);
    Wald    = T * h' * pinv(H * AsynCov * H') * h;
    p_value = 1 - chi2cdf(Wald,length(h));
    
    switch col
        case 1
    tab_moments = [tab_moments, [data_moments_NormX; nan], [model_moments_NormX; FVAL]];
        case {2,3}
    tab_moments = [tab_moments, [model_moments_NormX; FVAL]];
    end     

    tab_parameters = [tab_parameters, [reshape([theta, se]',[],1)]];
    tab_wald       = [tab_wald, [Wald; p_value]];

end


