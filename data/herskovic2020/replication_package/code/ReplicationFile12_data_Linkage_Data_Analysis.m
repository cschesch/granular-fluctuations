clear, addpath(genpath('functions\'))

%   COMPUSTAT DATA - VARIABLE DEFNS FROM LAUREN
%   dates - year of observation
%   permno - this is a unique firm identifier for the supplier firm
%   cpermno - this is a unique firm identifier for the customer firm
%   srcyr - source year
%   srcfyr - source fiscal year end
%   csale - sales of the supplier to given customer (in millions)
%   sale - total sales of supplier firm (in millions)
%   percsale - csale/sale
%   hsiccd - SIC code for the supplier
%   chsiccd - SIC code for the customer
%   Indus - Fama and French 49 industry classification code for supplier
%   cindus - Fama and French 49 industry classification code for customer
%   CSTYPE - N/A
%   CSID - N/A

%*********************************************************************
% Unique vertices by year
%*********************************************************************

% Load annual volatility variables
load('../output/CleanData/ALL DATA MERGED July2017')  % generated by 'ReplicationFile06_data_MergeDatasets.m'
datelist = ALL.yrlist;
permlist = ALL.permlist;
ME       = ALL.ME;
RV       = ALL.STOCKVOL1Y;
clear ALL

load('../output/CleanData/Cashflow_matrix_annual_1925_2016_July2017');  % generated by "ReplicationFile10_data_Build_Cash_Flow_Growth_Data.m"
load('../data/linkages2013')

% Note: Need to convert zero percsale to missing for degree calculations below
percsale(percsale<=0) = nan;

% Note: Treat as NaN if percsale>1
percsale(percsale>1) = nan;

% OPTION: USE THIS TO IMPOSE TRUNCATION
% percsale(percsale<.1) = nan;

% Note: NaN if supplier total sales negative or zero
sale(sale<=0)           = nan;

% Note: NaN if customer total sales negative or zero
ctotsale(ctotsale<=0)   = nan;

% Value of sales from specific customer
csale                   = percsale.*sale;

%*********************************************************************
% Aggregate by supplier-year
%*********************************************************************

% Unique years
yrlist     = unique(dates);
T          = length(yrlist);

% Count unique supplier-years
ns         = length(unique([permno dates],'rows'));

% Count unique customer-years
nc         = length(unique([cpermno dates],'rows'));

% Reserve memory
sizeout    = nan(ns,1);
linkout    = nan(ns,1);
herfout    = nan(ns,1);
rvout      = nan(ns,1);
sarvout    = nan(ns,1);
listout    = nan(ns,1);
yearout    = nan(ns,1);
wtsout     = nan(ns,1);
zwtsout     = nan(ns,1);

sizein     = nan(nc,1);
linkin     = nan(nc,1);
herfin     = nan(nc,1);
rvin       = nan(nc,1);
sarvin     = nan(nc,1);
listin     = nan(nc,1);
yearin     = nan(nc,1);
wtsin      = nan(nc,1);
zwtsin      = nan(nc,1);

outdeg_sales  = nan(T,1);
indeg_sales   = nan(T,1);
herfout_sales = nan(T,1);
herfout_rv    = nan(T,1);
herfout_sarv  = nan(T,1);
herfin_sales  = nan(T,1);
herfin_rv     = nan(T,1);
herfin_sarv   = nan(T,1);
wts_out       = nan(T,1);
wts_in        = nan(T,1);

outdegreedist = nan(T,5);
outdegreecorr = nan(T,1);
indegreedist  = nan(T,5);
indegreecorr  = nan(T,1);

outherfdist   = nan(T,3);
inherfdist    = nan(T,3);

lasts = 0;
lastc = 0;
for t=5:T;
    
    % Find indexes of compustat data
    loc            = find(dates == yrlist(t));
    [supplist ixs] = unique(permno(loc));
    [custlist ixc] = unique(cpermno(loc));
    
    % Find indexes of crsp data
    crspix         = find(datelist==yrlist(t));

    %***********************************************************
    % Supplier stats
    
    % Size
    suppsize       = sale(loc(ixs));

    Hout           = nan(size(supplist));
    outdeg         = nan(size(supplist));
    rvsupp         = nan(size(supplist));
    sarvsupp       = nan(size(supplist));
    wt_sz_out      = nan(size(supplist));        
    zwt_sz_out      = nan(size(supplist));        
    for i = 1:length(supplist)
        loc1       = find(permno(loc)==supplist(i));
        
        % Wts of each customer of supplier(i)
        wts        = percsale(loc(loc1));        
        % Total sales of each customer of supplier(i)
        cs         = ctotsale(loc(loc1));        
        
        % Supplier's herf and outdegree (omit from network if all wts are zero)
        h          = nansum(wts.^2);
        if h>0, 
            Hout(i)     = h;
            outdeg(i)   = nansum(wts>0);
        end
        
        % Corr b/w supplier's customer wts and customer sizes
        z               = find(~isnan(wts+cs));
        if length(z)>2
            wt_sz_out(i) = corr(wts(z),cs(z));
            zwt_sz_out(i) = length(z);
        end

        % Supplier's vol
        crspix1    = find(permlist==supplist(i));        
        if isempty(crspix1), continue, end
        rvsupp(i)  = RV(crspix,crspix1);
        sarvsupp(i)= Svol(crspix,crspix1);
    end
    Hout(Hout<=0 | Hout>1) = nan;
    
    %***********************************************************
    % Customer stats
    custsize       = ctotsale(loc(ixc));

    Hin            = nan(size(custlist));
    indeg          = nan(size(custlist));
    rvcust         = nan(size(custlist));
    sarvcust       = nan(size(custlist));
    wt_sz_in       = nan(size(custlist)); 
    zwt_sz_in       = nan(size(custlist)); 
    for i = 1:length(custlist)
        loc1       = find(cpermno(loc)==custlist(i));
        
        % Wts of each supplier of customer(i)
        wts        = csale(loc(loc1))/custsize(i);   
        wts = max(0,wts);
        wts( wts <= 0 | isinf(wts)) = nan; if max(wts) > 1, wts = wts / nansum(wts); end
        
        % Total sales of each supplier of customer(i)
        ss         = sale(loc(loc1));        
        
        if nansum(wts) <=0, continue, end
        % Customer's herf and outdegree (omit from network if all wts are zero)
        h          = nansum(wts.^2);
        if h>0, 
            Hin(i)      = h;
            indeg(i)    = nansum(wts>0);
        end
        
        % Corr b/w customer's supplier wts and supplier sizes
        z               = find(~isnan(wts+ss));
        if length(z)>2
            wt_sz_in(i) = corr(wts(z),ss(z));
            zwt_sz_in(i) = length(z);
        end
        
        crspix1    = find(permlist==custlist(i));
        if isempty(crspix1), continue, end
        rvcust(i)  = RV(crspix,crspix1);
        sarvcust(i)= Svol(crspix,crspix1);        
    end
    Hin(Hin<=0 | Hin>1) = nan;
    
    %***********************************************************
    % Cross section correlations by year

    % Calc Herf distn
    outherfdist(t,:)    = prctile(Hout,[50 75 99]);
    inherfdist(t,:)     = prctile(Hin,[50 75 99]);
    
    % Calc degree distn
    outdegreedist(t,:)  = prctile(outdeg,[50,75,90,99,99.9]);
    indegreedist(t,:)   = prctile(indeg,[50,75,90,99,99.9]);

    % Size / outdegree
    z                   = find(~isnan( outdeg+suppsize ));
    outdeg_sales(t,1)   = corr(outdeg(z),log(suppsize(z)));
    % Size / indegree
    z                   = find(~isnan( indeg+custsize ));
    indeg_sales(t,1)    = corr(indeg(z),log(custsize(z)));
    % Size / out-herf    
    z                   = find(~isnan( Hout+suppsize ));
    herfout_sales(t,1)  = corr((Hout(z)),log(suppsize(z)));
    % Size / in-herf
    z                   = find(~isnan( Hin+custsize ));
    herfin_sales(t,1)   = corr((Hin(z)),log(custsize(z)));
    % RV / out-herf    
    z                   = find(~isnan( Hout+rvsupp ));
    herfout_rv(t,1)     = corr((Hout(z)),(rvsupp(z)));
    
    % RV / in-herf    
    z                   = find(~isnan( Hin+rvcust ));
    herfin_rv(t,1)      = corr((Hin(z)),(rvcust(z)));

    % Sales RV / herf    
    % Note: Svol calculated using 5yr rolling window
    if t<=T-2
        z                   = find(~isnan( Hout+sarvsupp ));
        herfout_sarv(t,1)   = corr((Hout(z)),(sarvsupp(z)));

        z                   = find(~isnan( Hin+sarvcust ));
        herfin_sarv(t,1)    = corr((Hin(z)),(sarvcust(z)));
    end

    wts_out(t)              = nanmean(wt_sz_out);
    wts_in(t)               = nanmean(wt_sz_in);

    %***********************************************************
    % Save for pooled analysis
    newlasts                        = lasts+length(supplist);
    newlastc                        = lastc+length(custlist);
    listout(lasts+1:newlasts)       = supplist;
    listin(lastc+1:newlastc)        = custlist;
    yearout(lasts+1:newlasts)       = yrlist(t);
    yearin(lastc+1:newlastc)        = yrlist(t);
    sizeout(lasts+1:newlasts)       = suppsize;
    sizein(lastc+1:newlastc)        = custsize;
    herfout(lasts+1:newlasts)       = Hout;
    herfin(lastc+1:newlastc)        = Hin;
    rvout(lasts+1:newlasts)         = rvsupp;
    rvin(lastc+1:newlastc)          = rvcust;
    sarvout(lasts+1:newlasts)       = sarvsupp;
    sarvin(lastc+1:newlastc)        = sarvcust;
    linkout(lasts+1:newlasts)       = outdeg;
    linkin(lastc+1:newlastc)        = indeg;
    wtsout(lasts+1:newlasts)        = wt_sz_out;
    wtsin(lastc+1:newlastc)         = wt_sz_in;
    zwtsout(lasts+1:newlasts)        = zwt_sz_out;
    zwtsin(lastc+1:newlastc)         = zwt_sz_in;
    
    lasts = newlasts;
    lastc = newlastc;
    
    t
end
clear last* t *ix* loc* nc ns wts size ans supp* cust* h slist clist datelist *deg i H* 
clear RV Svol *permno *sale new* dates

annual_corr_table = ...
[yrlist wts_out outdeg_sales herfout_sales herfout_rv  herfout_sarv wts_in indeg_sales herfin_sales herfin_rv herfin_sarv];

annual_corr_table = [annual_corr_table;
[nan nanmean(annual_corr_table(:,2:end)); nan nanmean(annual_corr_table(:,2:end))./nanstd(annual_corr_table(:,2:end))]];

save('../output/CleanData/aggregated_linkage_data_July2017')
