%**************************************************************************

% The use table shows the uses of commodities by intermediate and final
% users. In contrast to the make table, the rows in the use table present the commodities
% or products, and the columns display the industries and final users that utilize
% them. The sum of the entries in a row is the output of that commodity. The columns
% show the products consumed by each industry and the three components of
% ?value added??compensation of employees, taxes on production and imports less
% subsidies, and gross operating surplus. Value added is the difference between an
% industry?s output and the cost of its intermediate inputs, and total value added is
% equal to GDP. The sum of the entries in a column is that industry?s output. 

load('../output/CleanData//BEA_1997_2015','IO_table','output_industry','output_commodity') % generated by "ReplicationFile24_Build_BEA_Network.m"
Table_Stats = [];

for truncation = [true false]

Moments = [];
for yr = 1997:2015

eval(['IO_tab = IO_table.yr' num2str(yr) ';'])
eval(['OutInd = output_industry.yr' num2str(yr) ';'])
eval(['OutCom = output_commodity.yr' num2str(yr) ';'])

W_dollar = IO_tab;

S_supp = sum(W_dollar,2); 
S_cust = sum(W_dollar,1)';

% Network' -- IO-tab rows are commodities (suppliers) and columns are industries (customers==users of the commodities)
W =  bsxfun(@times, IO_tab, 1 ./ sum(IO_tab,2));

if truncation
    in_star = (W >= 0.1); % indices for w threshold truncation (if model not 4)
    W = W .* in_star;
    IO_tab = IO_tab .* in_star;
end

Nout   = sum(W>0,2);   %  out-degree - supplier degree
Nin    = sum(W>0,1)';  %  in-degree  - customer degree

% Herfindahl (Hout)
Hout  = sum(W.^2,2);  %  Herfindahl (supplier)
Hout(Hout == 0) = nan;

  
% Herfindahl (Hin)
Sum_Waux = sum(W_dollar,1); Sum_Waux(Sum_Waux==0) = 1;
W_in = bsxfun(@times, W_dollar, 1 ./ Sum_Waux);

Hin = sum(W_in.^2,1)';
Hin(Hin == 0) = nan;

corr_wij_Sj = [];
for i = 1:65
    
    if sum(W(i,:) > 0) >= 5
    corr_wij_Sj = [corr_wij_Sj; corr(log(W(i,W(i,:) > 0))',log(S_cust(W(i,:) > 0)),'rows','pairwise')];
    end
    
    
end
loc_S = S_supp > 0;
Moments = [Moments, [nanmean(corr_wij_Sj); ...                      
            corr(log(S_supp(loc_S)), Nout(loc_S),'rows','pairwise');... 
            corr(log(S_supp(loc_S)), Hout(loc_S),'rows','pairwise');...
            corr(log(S_supp(loc_S)), Nin(loc_S),'rows','pairwise');...
            corr(log(S_supp(loc_S)), Hin(loc_S),'rows','pairwise');...
            ]];

end
Table_Stats = [Table_Stats, nanmean(Moments,2)];
end

Table_Stats_BEA_Trunc   = Table_Stats(:,1);
Table_Stats_BEA_NoTrunc = Table_Stats(:,2);


