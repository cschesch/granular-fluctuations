@dataclass(frozen=True)
class Population:
    """Everything fixed across replications for one (N, T, design) cell."""

    name: str
    n: int
    t: int
    sizes: np.ndarray
    whitening: np.ndarray
    price_direction: np.ndarray
    aggregate_direction: np.ndarray
    loadings: np.ndarray
    grouped_loadings: np.ndarray
    full_baseline_weight: np.ndarray
    full_oracle_weight: np.ndarray
    grouped_oracle: object
    diagnostics: dict[str, float]

    @property
    def factor_count(self) -> int:
        return int(self.loadings.shape[1])

    @property
    def true_combined_rank(self) -> int:
        return int(self.grouped_oracle.combined_rank)


def _project_off(vector: np.ndarray, span: np.ndarray) -> np.ndarray:
    """Project ``vector`` onto ``col(span)^perp`` without forming an N x N matrix."""

    q, _ = np.linalg.qr(span)
    return vector - q @ (q.T @ vector)


def _grouping_objects(n: int) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    sizes = power_law_sizes(n, ZETA)
    buckets, loads = lpt_buckets(sizes**2, M)
    grouping = np.zeros((M, n))
    for bucket_index, members in enumerate(buckets):
        grouping[bucket_index, members] = sizes[members]
    whitening = grouping / np.sqrt(loads)[:, None]
    price_direction = whitening @ np.ones(n)
    aggregate_direction = np.sqrt(loads)
    if not np.allclose(whitening @ whitening.T, np.eye(M), atol=2e-12):
        raise AssertionError("squared-size whitening did not produce spherical errors")
    if abs(aggregate_direction @ price_direction - 1.0) > 2e-12:
        raise AssertionError("grouped aggregate no longer has unit price loading")
    singletons = sum(1 for members in buckets if len(members) == 1)
    if singletons < CORE_UNITS or any(len(buckets[m]) != 1 for m in range(CORE_UNITS)):
        raise AssertionError("the core units are not LPT singletons in size order")
    return sizes, whitening, price_direction, aggregate_direction


def _loading_designs(n: int) -> dict[str, np.ndarray]:
    core = np.zeros(n)
    core[:CORE_UNITS] = math.sqrt(FACTOR_STRENGTH / CORE_UNITS)
    return {
        "core_weak": core[:, None],
    }


def build_population(n: int, t: int, name: str) -> Population:
    if (n, t) not in SAMPLES:
        raise ValueError("the design requires N=1000 and T in {100, 1000, 10000}")
    sizes, whitening, b, d = _grouping_objects(n)
    loadings = _loading_designs(n)[name]
    grouped_loadings = whitening @ loadings
    e = np.ones(n) / n
    q0 = sizes - e
    q_full = _project_off(sizes, np.column_stack((np.ones(n), loadings)))
    group_oracle = known_instrument_space(b, grouped_loadings, d)

    h = float(q0 @ q0)
    i_n = float(q_full @ q_full)
    i_g = float(group_oracle.information)
    no_factor_space = known_instrument_space(b, np.empty((M, 0)), d)
    i_g0 = float(no_factor_space.information)
    n_eff = float(b @ b)
    if grouped_loadings.shape[1]:
        r_b = orthogonal_complement(b[:, None])
        grouped_gap = float(np.linalg.norm(r_b.T @ grouped_loadings, ord="fro") ** 2)
        centered = loadings[:, 0] - loadings[:, 0].mean()
        centered_strength = float(centered @ centered)
        a = float(q0 @ loadings[:, 0])
        bb = float(loadings[:, 0].mean())
        rs = FACTOR_EPS_CORR * SIGMA_EPS
        plim_psi_bias = (1.0 - PSI * PHI) * a * rs / (a * (a + bb + PHI * rs) + SIGMA_E**2 * h)
        plim_phi_bias = (1.0 - PSI * PHI) * a * bb / (PSI * (a * a + a * bb + SIGMA_E**2 * h) + a * rs)
    else:
        grouped_gap = 0.0
        centered_strength = 0.0
        a = bb = 0.0
        plim_psi_bias = plim_phi_bias = 0.0
    bbp_boundary = math.sqrt(n / t) * SIGMA_E**2
    diagnostics = {
        "N": n,
        "T": t,
        "M": M,
        "factor_count": loadings.shape[1],
        "factor_strength": float(np.sum(loadings**2)),
        "centered_strength": centered_strength,
        "bbp_boundary": bbp_boundary,
        "bbp_ratio": centered_strength / bbp_boundary,
        "full_hahn_bic_margin_lower_bound": math.log(t) - t / (2.0 * (n - 1)),
        "grouped_gap": grouped_gap,
        "residual_dimension": group_oracle.residual_dimension,
        "I_0": h,
        "I_N": i_n,
        "I_G": i_g,
        "I_G_no_factor": i_g0,
        "oracle_se_ratio_N_over_G": math.sqrt(i_n / i_g) if i_g > 0 else float("inf"),
        "oracle_se_ratio_0_over_N": math.sqrt(h / i_n) if i_n > 0 else float("inf"),
        "oracle_se_ratio_0_over_G": math.sqrt(h / i_g) if i_g > 0 else float("inf"),
        "N_eff": n_eff,
        "singleton_buckets": int(np.sum(np.abs(b - 1.0) < 1e-12)),
        "largest_share": float(sizes[0]),
        "sum_S2": float(sizes @ sizes),
        "a_instrument_loading": a,
        "b_mean_loading": bb,
        "plim_psi_bias_omitted": plim_psi_bias,
        "plim_phi_bias_omitted": plim_phi_bias,
    }
    return Population(
        name=name,
        n=n,
        t=t,
        sizes=sizes,
        whitening=whitening,
        price_direction=b,
        aggregate_direction=d,
        loadings=loadings,
        grouped_loadings=grouped_loadings,
        full_baseline_weight=q0,
        full_oracle_weight=q_full,
        grouped_oracle=group_oracle,
        diagnostics=diagnostics,
    )


def _pca_loading(panel: np.ndarray, factor_count: int) -> np.ndarray:
    """Leading loading directions of the cross-sectionally demeaned panel.

    Works in the T x T Gram matrix: the top eigenvectors of X'X are X'v for
    the top eigenvectors v of XX'.  Returns an N x r matrix (r may be zero).
    """

    t, n = panel.shape
    if factor_count == 0:
        return np.empty((n, 0))
    centered = panel - panel.mean(axis=1, keepdims=True)
    gram = centered @ centered.T
    _, vectors = sla.eigh(gram, subset_by_index=[t - factor_count, t - 1])
    return centered.T @ vectors


def _full_spectral(pop: Population, x: np.ndarray) -> tuple[np.ndarray, tuple | None]:
    """Apply the original BIC directly when the projected covariance is full rank."""
    t, n = x.shape
    if t < n - 1:
        return _pca_loading(x, pop.factor_count), None
    v = np.ones(n) / math.sqrt(n)
    v[0] += 1.0
    v /= np.linalg.norm(v)
    projected = x[:, 1:] - np.outer(x @ v, 2.0 * v[1:])
    covariance = projected.T @ projected / t
    eigvals = sla.eigh(covariance, eigvals_only=True)
    rank, bic = hahn_bic(eigvals, t)
    count = max(pop.factor_count, rank - 1)
    if count:
        _, vectors = sla.eigh(covariance, subset_by_index=[n - 1 - count, n - 2])
        directions = np.vstack((np.zeros((1, count)), vectors))
        directions -= np.outer(v, 2.0 * (v @ directions))
    else:
        directions = np.empty((n, 0))
    pca = (directions[:, -pop.factor_count:] * np.sqrt(t * eigvals[-pop.factor_count:])
           if pop.factor_count else np.empty((n, 0)))
    weight = pop.full_baseline_weight.copy()
    if rank > 1:
        factors = directions[:, -(rank - 1):]
        weight -= factors @ (factors.T @ weight)
        gap = float(eigvals[-(rank - 1)] - eigvals[0])
    else:
        gap = float("nan")
    ordered_bic = np.sort(bic)
    margin = float(ordered_bic[1] - ordered_bic[0])
    return pca, (weight, rank, gap, margin)


