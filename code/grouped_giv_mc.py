def _bic_margin(space: object) -> float:
    values = np.asarray(space.bic_values, dtype=float)
    if values.size < 2 or not np.isfinite(values).all():
        return float("nan")
    ordered = np.sort(values)
    return float(ordered[1] - ordered[0])


def _full_panel(
    pop: Population, x: np.ndarray, weight: np.ndarray, price: np.ndarray, aggregate: np.ndarray
) -> tuple[EquationEstimate, EquationEstimate]:
    instrument = (x @ weight)[:, None]
    equal_outcome = x.mean(axis=1)
    one = np.ones(1)
    return (
        scalar_iv(instrument, one, equal_outcome, price),
        scalar_iv(instrument, one, price, aggregate),
    )


def _grouped_scalar(
    pop: Population, grouped_x: np.ndarray, space: object, price: np.ndarray, aggregate: np.ndarray
) -> tuple[EquationEstimate, EquationEstimate]:
    b, d = pop.price_direction, pop.aggregate_direction
    weight = projected_weight(space, d)
    upsilon = space.upsilon if space.estimated else None
    reference = grouped_x @ b / float(b @ b)
    return (
        scalar_iv(grouped_x, weight, reference, price, upsilon=upsilon),
        scalar_iv(grouped_x, weight, price, aggregate, upsilon=upsilon),
    )


def bai_ng_count(eigenvalues, total_variance, t, dimension):
    """ICp2 on the price-orthogonal panel, avoiding near-saturation at M=10."""
    cap = min(BAI_NG_MAX_FACTORS, dimension - 1, t - 1)
    counts = np.arange(cap + 1)
    unexplained = total_variance - np.r_[0.0, np.cumsum(eigenvalues[:cap])]
    # The divisor in residual variance is constant across candidate ranks.
    penalty = (1 / t + 1 / dimension) * np.log(min(t, dimension))
    scores = np.log(np.maximum(unexplained / total_variance, np.finfo(float).eps))
    return int(np.argmin(scores + counts * penalty))


def bai_ng_weight(x, price_direction, aggregate_direction, spectrum=None):
    """Project aggregate weights off price and the selected PCA loading space."""
    t, m = x.shape
    dimension = m - 1
    unit_price = price_direction / np.linalg.norm(price_direction)
    if spectrum is not None:
        values, vectors = spectrum
        count = bai_ng_count(values[::-1], values.sum(), t, dimension)
        loadings = vectors[:, dimension - count:]
    else:
        residual = x - np.outer(x @ unit_price, unit_price)
        cap = min(BAI_NG_MAX_FACTORS, dimension - 1, t - 1)
        if cap == 0:
            return _project_off(aggregate_direction, unit_price[:, None]), 0
        short = t < m
        matrix = residual.T if short else residual
        gram = sla.blas.dsyrk(1 / t, matrix.T, lower=1)
        values, vectors = sla.eigh(gram, lower=True, subset_by_index=(len(gram) - cap, len(gram) - 1))
        count = bai_ng_count(values[::-1], np.trace(gram), t, dimension)
        loadings = vectors[:, cap - count:]
        if short:
            loadings = residual.T @ loadings
    return _project_off(aggregate_direction, np.column_stack((unit_price, loadings))), count


def bai_ng_records(pop, replication, x, grouped, price, aggregate, spectrum=None):
    ones = np.ones(pop.n)
    b, d = pop.price_direction, pop.aggregate_direction
    weight, count = bai_ng_weight(x, ones, pop.sizes, spectrum)
    phi, psi = _full_panel(pop, x, weight, price, aggregate)
    yield _record(pop, replication, "full_bai_ng", phi, psi,
                  selected_rank=count + 1, information=float(weight @ weight))

    weight, count = bai_ng_weight(grouped, b, d)
    reference = grouped @ b / float(b @ b)
    phi = scalar_iv(grouped, weight, reference, price)
    psi = scalar_iv(grouped, weight, price, aggregate)
    yield _record(pop, replication, "group_bai_ng", phi, psi,
                  selected_rank=count + 1, information=float(weight @ weight))


def simulate_cell(pop: Population, reps: int, rng: np.random.Generator) -> list[dict[str, object]]:
    """Run all methods on each dataset before drawing the next."""
    n, t = pop.n, pop.t
    loading = pop.loadings[:, 0] if pop.factor_count else np.zeros(n)
    unit_loading = loading / np.linalg.norm(loading) if pop.factor_count else None
    aggregate_loading = float(pop.sizes @ loading)
    baseline_loading = float(pop.full_baseline_weight @ loading)
    b, d = pop.price_direction, pop.aggregate_direction
    denominator = 1.0 - PHI * PSI
    ones_n = np.ones(n)
    started = time.time()
    rows: list[dict[str, object]] = []

    for replication in range(reps):
        factor = rng.standard_normal(t)
        eps_innovation = rng.standard_normal(t)
        epsilon = SIGMA_EPS * (
            FACTOR_EPS_CORR * factor
            + math.sqrt(1.0 - FACTOR_EPS_CORR**2) * eps_innovation
        )
        error = rng.standard_normal((t, n)) * SIGMA_E
        aggregate = (PHI * epsilon + aggregate_loading * factor + error @ pop.sizes) / denominator
        price = PSI * aggregate + epsilon
        x = error
        x += np.outer(price, PHI * ones_n)
        if pop.factor_count:
            x += np.outer(factor, loading)
        grouped_x = x @ pop.whitening.T
        if replication == 0 and not np.allclose(grouped_x @ d, aggregate, atol=1e-8):
            raise AssertionError("simulated grouped system does not aggregate to y")

        rows.extend(bai_ng_records(pop, replication, x, grouped_x, price, aggregate))
        # Full-panel PCA-GIV with the true factor count.
        pca_loadings, hahn = _full_spectral(pop, x)
        span = np.column_stack((ones_n, pca_loadings))
        pca_weight = _project_off(pop.sizes, span)
        if pop.factor_count:
            overlap = float((unit_loading @ pca_loadings[:, 0]) ** 2 / (pca_loadings[:, 0] @ pca_loadings[:, 0]))
            leak = float(pca_weight @ loading / baseline_loading) if baseline_loading else float("nan")
        else:
            overlap = leak = float("nan")
        phi_e, psi_e = _full_panel(pop, x, pca_weight, price, aggregate)
        rows.append(_record(
            pop, replication, "full_pca", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=float(pca_weight @ pca_weight),
            pca_overlap=overlap, factor_leak=leak,
        ))


        # Algorithm 1 requires the ordinary inverse of the full 2K covariance.
        reason = joint_covariance_failure(t, n - pop.true_combined_rank)
        if reason:
            phi_e = psi_e = _failed_equation(reason)
        else:
            full_space = estimated_instrument_space(x, ones_n, pop.sizes,
                                                   combined_rank=pop.true_combined_rank)
            joint = estimate_joint_giv(x, price, aggregate, ones_n, pop.sizes, full_space)
            phi_e, psi_e = joint.phi, joint.psi
        rows.append(_record(
            pop, replication, "full_rank_known", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=float(pca_weight @ pca_weight),
        ))

        if hahn is None:
            phi_e = psi_e = _failed_equation("original BIC undefined: singular projected covariance")
            selected_rank, information = -1, float("nan")
            gap = margin = float("nan")
        else:
            weight, selected_rank, gap, margin = hahn
            information = float(weight @ weight)
            reason = joint_covariance_failure(t, n - selected_rank)
            if reason:
                phi_e = psi_e = _failed_equation(reason)
            else:
                full_space = estimated_instrument_space(x, ones_n, pop.sizes)
                joint = estimate_joint_giv(x, price, aggregate, ones_n, pop.sizes, full_space)
                phi_e, psi_e = joint.phi, joint.psi
        rows.append(_record(
            pop, replication, "full_hahn", phi_e, psi_e,
            selected_rank=selected_rank, information=information,
            eigengap=gap, bic_margin=margin,
        ))

        phi_e, psi_e = _full_panel(pop, x, pop.full_oracle_weight, price, aggregate)
        rows.append(_record(
            pop, replication, "full_oracle", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=pop.diagnostics["I_N"],
        ))

        phi_e, psi_e = _grouped_scalar(pop, grouped_x, pop.grouped_oracle, price, aggregate)
        rows.append(_record(
            pop, replication, "group_oracle", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=pop.diagnostics["I_G"],
        ))

        feasible_space = estimated_instrument_space(grouped_x, b, d)
        joint = estimate_joint_giv(grouped_x, price, aggregate, b, d, feasible_space)
        phi_e, psi_e = joint.phi, joint.psi
        rows.append(_record(
            pop, replication, "group_feasible", phi_e, psi_e,
            selected_rank=feasible_space.combined_rank, information=feasible_space.information,
            eigengap=feasible_space.eigengap, bic_margin=_bic_margin(feasible_space),
        ))

        rank_known_space = estimated_instrument_space(
            grouped_x, b, d, combined_rank=pop.true_combined_rank
        )
        group_pca_weight = projected_weight(rank_known_space, d)
        group_reference = grouped_x @ b / float(b @ b)
        phi_e = scalar_iv(grouped_x, group_pca_weight, group_reference, price)
        psi_e = scalar_iv(grouped_x, group_pca_weight, price, aggregate)
        rows.append(_record(
            pop, replication, "group_pca", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=rank_known_space.information,
            eigengap=rank_known_space.eigengap,
        ))

        joint = estimate_joint_giv(grouped_x, price, aggregate, b, d, rank_known_space)
        phi_e, psi_e = joint.phi, joint.psi
        rows.append(_record(
            pop, replication, "group_rank_known", phi_e, psi_e,
            selected_rank=pop.true_combined_rank, information=rank_known_space.information,
            eigengap=rank_known_space.eigengap, bic_margin=_bic_margin(rank_known_space),
        ))

        if (replication + 1) % 100 == 0:
            print(f"[grouped_giv_mc] {pop.name}, N={n}, T={t}: "
                  f"{replication + 1}/{reps} datasets", flush=True)
    print(f"[grouped_giv_mc] {pop.name}, T={t}: {reps} datasets "
          f"in {time.time()-started:.0f}s", flush=True)
    return rows


def summarize(draws: pd.DataFrame, reps: int) -> pd.DataFrame:
    rows = []
    truth = {"phi": PHI, "psi": PSI}
    keys = ["N", "T", "design", "method"]
    for (n, t, design, method), block in draws.groupby(keys, sort=False):
        if len(block) != reps or block["replication"].nunique() != reps:
            raise ValueError("each sample/design/method cell must contain exactly reps datasets")
        row: dict[str, object] = {
            "N": int(n),
            "T": int(t),
            "design": design,
            "design_label": DESIGN_LABEL[design],
            "method": method,
            "method_label": METHOD_LABEL[method],
            "rank_rule": (
                "Bai–Ng ICp2" if method in BAI_NG_METHODS
                else "undefined BIC" if method == "full_hahn" and t < n - 1
                else "BIC" if method in ("full_hahn", "group_feasible") else "oracle"
            ),
            "replications": reps,
            "available": bool((~block["phi_failed"] & ~block["psi_failed"]).any()),
            "unavailable_reason": (
                "BIC" if block["psi_failure"].str.contains("original BIC").all()
                else "GMM" if block["psi_failed"].all() else ""
            ),
            "rank_correct": float(block["rank_correct"].mean()),
            "factor_selected": float(block["selected_rank"].ge(2).mean()),
            "mean_selected_rank": float(block["selected_rank"].mean()),
            "median_information": float(block["information"].median()),
            "median_eigengap": float(block["eigengap"].median()),
            "median_bic_margin": float(block["bic_margin"].median()),
            "mean_pca_overlap": float(block["pca_overlap"].mean()),
            "mean_factor_leak": float(block["factor_leak"].mean()),
        }
        for parameter in ("phi", "psi"):
            failed = block[f"{parameter}_failed"].to_numpy(bool)
            estimate = block[f"{parameter}_hat"].to_numpy(float)
            se = block[f"{parameter}_se"].to_numpy(float)
            naive_se = block[f"{parameter}_naive_se"].to_numpy(float)
            valid = ~failed & np.isfinite(estimate) & np.isfinite(se)
            errors = estimate[valid] - truth[parameter]
            row[f"{parameter}_bias"] = float(np.mean(errors)) if errors.size else float("nan")
            row[f"{parameter}_median_bias"] = float(np.median(errors)) if errors.size else float("nan")
            row[f"{parameter}_sd"] = float(np.std(estimate[valid], ddof=1)) if errors.size > 1 else float("nan")
            row[f"{parameter}_rmse"] = float(np.sqrt(np.mean(errors**2))) if errors.size else float("nan")
            row[f"{parameter}_mean_se"] = float(np.mean(se[valid])) if errors.size else float("nan")
            row[f"{parameter}_coverage"] = float(
                np.sum(valid & (np.abs(estimate - truth[parameter]) <= CI_CRITICAL * se)) / reps
            )
            row[f"{parameter}_naive_coverage"] = float(
                np.sum(valid & np.isfinite(naive_se)
                       & (np.abs(estimate - truth[parameter]) <= CI_CRITICAL * naive_se)) / reps
            )
            row[f"{parameter}_failure"] = float(1.0 - valid.mean())
            row[f"{parameter}_se_correction_ratio"] = (
                float(np.mean(se[valid] / naive_se[valid])) if errors.size else float("nan")
            )
            strength = block[f"{parameter}_strength"].to_numpy(float)
            row[f"{parameter}_mean_strength"] = float(np.mean(strength[valid])) if errors.size else float("nan")
            jp = block[f"{parameter}_j_pvalue"].to_numpy(float)
            has_j = valid & np.isfinite(jp)
            row[f"{parameter}_j_rejection"] = (
                float(np.sum(has_j & (jp < 0.05)) / np.sum(has_j)) if np.any(has_j) else float("nan")
            )
        if not row["available"]:
            # Inapplicability is distinct from zero coverage of valid intervals.
            for column in ("phi_coverage", "phi_naive_coverage", "psi_coverage", "psi_naive_coverage"):
                row[column] = float("nan")
        rows.append(row)
    summary = pd.DataFrame(rows)
    for (n, t, design), block in summary.groupby(["N", "T", "design"], sort=False):
        oracle = block[block["method"].eq("full_oracle")].iloc[0]
        for parameter in ("phi", "psi"):
            summary.loc[block.index, f"{parameter}_sd_ratio_to_full_oracle"] = (
                block[f"{parameter}_sd"] / oracle[f"{parameter}_sd"]
            )
    summary["method_order"] = summary["method"].map({m: i for i, m in enumerate(METHODS)})
    summary["design_order"] = summary["design"].map({d: i for i, d in enumerate(DESIGNS)})
    return summary.sort_values(["design_order", "N", "T", "method_order"]).reset_index(drop=True)


def _fmt(value: float, decimals: int = 3, *, percent: bool = False) -> str:
    if not np.isfinite(value):
        return "--"
    if percent:
        return f"{100.0 * value:.{decimals}f}"
    if round(value, decimals) == 0:
        value = 0.0  # suppress negative zero in small Monte Carlo biases
    return f"{value:.{decimals}f}"


def table_lines(summary: pd.DataFrame, parameter: str) -> list[str]:
    if parameter not in ("phi", "psi"):
        raise ValueError("parameter must be phi or psi")
    blocks = [(n, t) for n, t in SAMPLES]
    header_cells = " & ".join(
        rf"\multicolumn{{3}}{{c}}{{$T={t}$}}" for n, t in blocks
    )
    rules = "".join(
        rf"\cmidrule(lr){{{2 + 3 * k}-{4 + 3 * k}}}" for k in range(len(blocks))
    )
    lines = [
        HEADER.rstrip(),
        r"\begin{tabular}{l" + "rrr" * len(blocks) + "}",
        r"\toprule",
        "& " + header_cells + r" \\",
        rules,
        "& " + " & ".join(["Bias & SD & Coverage"] * len(blocks)) + r" \\",
        r"\midrule",
    ]
    for design_index, design in enumerate(DESIGNS):
        for method in METHODS:
            if method in ("full_oracle", "group_oracle"):
                if method == "group_oracle":
                    lines.append(r"\addlinespace")
                title = "Full-panel GIV" if method == "full_oracle" else "Grouped GIV"
                lines.append(rf"\multicolumn{{{1 + 3 * len(blocks)}}}{{l}}{{\textit{{{title}}}}} \\")
            cells = [METHOD_LABEL[method]]
            for n, t in blocks:
                row = summary[
                    summary["design"].eq(design) & summary["N"].eq(n)
                    & summary["T"].eq(t) & summary["method"].eq(method)
                ].iloc[0]
                if not row.get("available", True):
                    cells.extend(["---", "---", "---"])
                else:
                    cells.extend([
                        _fmt(row[f"{parameter}_bias"], 3),
                        _fmt(row[f"{parameter}_sd"], 3),
                        _fmt(row[f"{parameter}_coverage"], 1, percent=True),
                    ])
            lines.append(" & ".join(cells) + r" \\")
        if design_index < len(DESIGNS) - 1:
            lines.append(r"\addlinespace")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    return lines


def write_combined_table(summary: pd.DataFrame, path: Path) -> None:
    """One tabular with psi and phi panels, to be placed in one table float."""
    psi = table_lines(summary, "psi")
    phi = table_lines(summary, "phi")
    parts = []
    for lines, title in ((psi, r"Panel A: Price impact, $\psi=1.5$"),
                         (phi, r"Panel B: Spillover, $\phi=-0.5$")):
        body = lines[lines.index(r"\midrule")+1:lines.index(r"\bottomrule")]
        parts.append([rf"\multicolumn{{{1 + 3 * len(SAMPLES)}}}{{l}}{{\textbf{{{title}}}}} \\",
                      r"\addlinespace", *body])
    header = psi[:psi.index(r"\midrule")+1]
    lines = [*header, *parts[0], r"\midrule", *parts[1],
             r"\bottomrule", r"\end{tabular}"]
    # Fit the widest heading inside each equal-width column. Offset the
    # added content width with padding so the total table width is preserved.
    sizing = [
        r"\begingroup",
        r"\setbox0=\hbox{-0.219}\dimen0=\wd0",
        r"\setbox0=\hbox{1.383}\advance\dimen0 by\wd0",
        r"\setbox0=\hbox{Coverage}\advance\dimen0 by\wd0",
        r"\divide\dimen0 by 3",
        r"\setbox0=\hbox{Coverage}\dimen2=\wd0",
        r"\advance\dimen2 by-\dimen0",
        rf"\multiply\dimen2 by {3 * len(SAMPLES)}",
        rf"\divide\dimen2 by {2 * (1 + 3 * len(SAMPLES))}",
        r"\advance\tabcolsep by-\dimen2",
        r"\edef\givmcnumwidth{\the\wd0}",
        r"\newcommand{\givmcnum}[1]{\makebox[\givmcnumwidth][c]{#1}}",
        r"\newcommand{\givmchead}[1]{\makebox[\givmcnumwidth][c]{#1}}",
    ]
    equal_width = []
    for line in lines:
        if line.startswith(r"\cmidrule(lr)"):
            line = line.replace("(lr)", r"(l{\tabcolsep}r{\tabcolsep})")
        if " & " in line and r"\multicolumn" not in line:
            cells = [cell.strip() for cell in line.removesuffix(r" \\").split("&")]
            command = "givmchead" if not cells[0] else "givmcnum"
            line = " & ".join([cells[0], *(rf"\{command}{{{c}}}" for c in cells[1:])]) + r" \\"
        equal_width.append(line + "%" if line == r"\end{tabular}" else line)
    # Suppress whitespace outside the tabular so its measured width is preserved.
    path.write_text("\n".join([equal_width[0], *(line + "%" for line in sizing),
                                *equal_width[1:], r"\endgroup"]) + "\n")
