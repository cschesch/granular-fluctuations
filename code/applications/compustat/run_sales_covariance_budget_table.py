#!/usr/bin/env python3
"""Compute the row-l1 Compustat sensitivity table afresh; point estimates only.

Uses the unchanged baseline panel, weights, and LPT partition. The SDP is
expressed in standardized bucket averages, an exact rescaling of eq:l1_grouped_mgp.
Does not read previous estimates, run inference, or edit the manuscript.
"""
from wrds_inputs import wrds_path, ANALYSIS_LAST_QUARTER
import argparse
import json
import numpy as np
import pandas as pd
from applications.compustat import run_compustat_quarterly as quarterly
from mgp_core import (OUTPUT_DIR, RUN_OUTPUT_CACHE, atomic_write_pickle,
                      build_lpt_grouped_data, sample_cov)
import cvxpy as cp


def solve_covariance_budget(cov, weights, parameter, nu):
    m = len(weights)
    b = cp.Variable((m, m), symmetric=True)
    constraints = [b >> 0, cov-b >> 0]
    off = b - cp.diag(cp.diag(b))
    constraints += [cp.abs(off) @ nu <= parameter]
    problem = cp.Problem(cp.Maximize(cp.sum(cp.multiply(np.outer(weights, weights), b))), constraints)
    problem.solve(solver='CLARABEL', tol_gap_abs=1e-10, tol_feas=1e-10, tol_gap_rel=1e-10, max_iter=500)
    assert problem.status == 'optimal', problem.status
    value = np.asarray(b.value)
    residuals = [np.linalg.eigvalsh(value).min(), np.linalg.eigvalsh(cov-value).min()]
    off = value - np.diag(np.diag(value))
    residuals.append(float(np.min(parameter - np.abs(off) @ nu)))
    assert min(residuals) > -1e-7, residuals
    return float(problem.value), float(min(residuals))


BUDGETS = (0., .05, .10, .20, .50, 1.)


def write_table(frame):
    lines = [
        '% Generated by code/applications/compustat/run_sales_covariance_budget_table.py; do not edit.',
        r'\begingroup', r'\setlength{\tabcolsep}{0pt}',
        r'\begin{tabular}{@{}*{2}{>{\centering\arraybackslash}p{0.36\textwidth}}@{}}',
        r'\toprule', r'$\tau/\sigma^2_{\mathrm{med}}$ & Granularity ceiling (\%)\\',
        r'\midrule',
    ]
    for row in frame.itertuples():
        number = ""
        if pd.notna(row.ceiling):
            number = f'{100 * row.ceiling:.2f}'
            if 100 * row.ceiling < 10:
                number = r'\phantom{0}' + number
        lines.append(f'{row.tau_over_median_variance:.2f} & {number}' + r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\endgroup']
    path = OUTPUT_DIR / 'table_sales_covariance_budget_tabular.tex'
    path.write_text('\n'.join(lines) + '\n')
    print(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blank", action="store_true")
    if parser.parse_args().blank:
        write_table(pd.DataFrame({"tau_over_median_variance": BUDGETS, "ceiling": np.nan}))
        return
    panel = quarterly.load_compustat_panel(argparse.Namespace(
        compustat_csv=wrds_path("compustat_quarterly_sales"),
        last_date=ANALYSIS_LAST_QUARTER, T=100, coverage_threshold=.8))
    shares = panel.sizes.to_numpy(float).copy(); shares /= shares.sum()
    y = panel.wide.to_numpy(float)
    x, buckets, _, g = build_lpt_grouped_data(y, shares, 10)
    s = g.sum(axis=1)
    vmed = float(np.median(np.var(y, axis=1, ddof=1)))
    cov = sample_cov(x) / np.outer(s, s) / vmed
    aggregate = float(s @ cov @ s)
    # nu_l = tilde S_l / S_l^max; transforms the row constraints exactly.
    nu = s / g.max(axis=1)
    rows = []
    for multiple in BUDGETS:
        value, residual = solve_covariance_budget(cov, s, multiple, nu)
        rows.append(dict(tau_over_median_variance=multiple, tau=multiple*vmed,
                         ceiling=value/aggregate, min_constraint_slack=residual))
    frame = pd.DataFrame(rows)
    assert (np.diff(frame.ceiling) >= -1e-7).all()
    metadata = dict(N=len(shares), M=10, T=y.shape[1],
                    sample=[str(panel.start_date), str(panel.last_date)],
                    median_observed_firm_growth_variance=vmed,
                    aggregate_variance=aggregate*vmed,
                    solver='CLARABEL', inference=False,
                    specification='eq:l1_grouped_mgp', partition='baseline LPT')
    assert (metadata['M'], metadata['T']) == (10, 100)
    stem = 'compustat_covariance_budget'
    atomic_write_pickle(dict(rows=frame, metadata=metadata, buckets=buckets),
                        RUN_OUTPUT_CACHE/f'{stem}_summary.pkl')
    (RUN_OUTPUT_CACHE/f'{stem}_audit.json').write_text(json.dumps(metadata, indent=2)+'\n')
    write_table(frame)
    print(frame[['tau_over_median_variance', 'ceiling']].to_string(index=False))


if __name__ == '__main__':
    main()
