#!/usr/bin/env python3
"""Pair the main applications table with the cached homoskedastic estimates.

Preserves the main table's metadata and heteroskedastic estimates. The figure
contains 42 applications; the two additional annual Compustat rows use the
same hMGP implementation and 1000-draw inference. Does not edit main.tex.
"""
import argparse
import hashlib
import numpy as np
import pandas as pd

import build_applications_vertical as vertical
import run_homoskedastic_mgp as hom
from mgp_core import atomic_write_pickle

OUT = vertical.OUT
CACHE = vertical.CACHE
STEM = "table_applications_homoskedastic"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", nargs="+", help="Refresh selected applications; preserve all other cached rows")
    args = parser.parse_args()
    metadata = pd.read_csv(CACHE / "table_applications_vertical_data.csv")
    selected_applications = set(args.only or [])
    if selected_applications - set(metadata.application):
        raise ValueError(f"Unknown applications: {selected_applications - set(metadata.application)}")
    prior = pd.read_pickle(CACHE / f"{STEM}_summary.pkl").set_index("application") if args.only else None
    figure = pd.read_csv(CACHE / "applications_coefficients_expanded_data.csv").set_index("item")
    estimates = pd.read_csv(CACHE / "hmgp_figure1_data.csv").set_index("item")
    hierarchy = dict(hom.HIERARCHY)
    joined = []
    annual_path = CACHE / "hmgp_annual_compustat_table.pkl"
    annual = pd.read_pickle(annual_path) if annual_path.exists() else {}
    for section, applications in vertical.SECTIONS:
        plotted_apps = [a for a in applications if a not in ("Sales (annual)", "Productivity (annual)")]
        assert len(plotted_apps) == len(hierarchy[section])
        mapping = dict(zip(plotted_apps, hierarchy[section]))
        for application in applications:
            if selected_applications and application not in selected_applications:
                joined.append({**prior.loc[application].to_dict(), "application": application})
                continue
            selected = metadata[metadata.application.eq(application)]
            assert len(selected) == 1, application
            row = selected.iloc[0].to_dict()
            if pd.isna(row["estimate"]):
                joined.append(dict(row, homoskedastic_estimate=np.nan, homoskedastic_ucl95=np.nan))
                continue
            if application in mapping:
                item = mapping[application]
                q = estimates.loc[item]
                original = figure.loc[item]
                assert np.isclose(row["estimate"], original.estimate, atol=1e-12)
                assert np.isclose(row["ci_high"], original.high, atol=1e-12)
            else:
                prefix, clean = (("compustat_ann_sales", "compustat_annual_sale")
                                 if application == "Sales (annual)" else
                                 ("compustat_ann_tfp", "compustat_annual_tfp"))
                inputs = hom.core_panel(prefix, clean)
                signature = hashlib.sha256(inputs[0].tobytes() + inputs[1].tobytes()).hexdigest()
                if application not in annual or annual[application].get("input_fingerprint") != signature:
                    annual[application] = hom.hmgp(*inputs, seed=20260916)
                    annual[application]["input_fingerprint"] = signature
                    atomic_write_pickle(annual, annual_path)
                q = pd.Series(annual[application])
            assert tuple(int(row[c]) for c in ("N", "T", "M")) == tuple(int(q[c]) for c in ("N", "T", "M")), application
            row.update(homoskedastic_estimate=float(q.hmgp), homoskedastic_ucl95=float(q.h_hi))
            assert row["homoskedastic_estimate"] <= row["estimate"] + 1e-7, application
            joined.append(row)
    table = pd.DataFrame(joined)
    assert len(table) == len(metadata) == 44
    atomic_write_pickle(table, CACHE / f"{STEM}_summary.pkl")
    table.to_csv(CACHE / f"{STEM}_data.csv", index=False)
    lines = ["% Generated by code/build_homoskedastic_applications_table.py. Do not edit.",
             r"{\setlength{\tabcolsep}{3pt}%", r"\renewcommand{\arraystretch}{1.0}%",
             r"\begin{tabular}{@{}lllcr@{--}lrrrr@{}}", r"\toprule",
             r" & & & & \multicolumn{2}{c}{} & \multicolumn{2}{c}{Heteroskedastic} & \multicolumn{2}{c}{Homoskedastic} \\",
             r"\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
             r"Outcome & Unit & Source & Freq. & \multicolumn{2}{c}{Sample} & $\hat{\tilde\gamma}$ & 95\% UCL & $\hat{\tilde\gamma}$ & 95\% UCL \\",
             r"\midrule"]
    for section, applications in vertical.SECTIONS:
        lines += [r"\addlinespace[2pt]", rf"\multicolumn{{10}}{{@{{}}l}}{{\textit{{{section}}}}} \\"]
        for application in applications:
            row = table[table.application.eq(application)].iloc[0]
            cells = [vertical.fmt_text(row.outcome).replace("CO2", r"CO$_2$"),
                     vertical.fmt_text(row.unit), vertical.fmt_text(row.source),
                     vertical.fmt_text(row.frequency), vertical.split_sample(row["sample"]),
                     vertical.fmt_pct(row.estimate), vertical.fmt_ucl(row.ci_high),
                     vertical.fmt_pct(row.homoskedastic_estimate), vertical.fmt_ucl(row.homoskedastic_ucl95)]
            lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    (OUT / f"{STEM}.tex").write_text("\n".join(lines)+"\n")
    print(table[["application", "estimate", "ci_high", "homoskedastic_estimate", "homoskedastic_ucl95"]].to_string(index=False))
    hom.plot()


if __name__ == "__main__":
    main()
